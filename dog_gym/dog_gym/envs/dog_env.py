# otherwise. 4.5s matches the more generous LEG_PHASE_TERMINATION_S
# budget above.
NO_PROGRESS_GRACE_S = 4.5
NO_PROGRESS_MIN_DISTANCE_M = 0.05


def load_motor_joint_names(motor_mapping_path=DEFAULT_MOTOR_MAPPING_PATH):
    """Returns MJCF joint names ["leg_a_thigh", ...] indexed motor 1..8,
    resolved from motor_mapping.yaml's {leg, joint} pairs -- the same file
    dog_deploy uses, so sim and real can never disagree on motor ordering.
    """
    with open(motor_mapping_path) as f:
        mapping = yaml.safe_load(f)['motors']
    return [
        f"{mapping[motor_id]['leg']}_{mapping[motor_id]['joint']}"
        for motor_id in range(1, NUM_MOTORS + 1)
    ]


class DogEnv(gym.Env):
    metadata = {'render_modes': ['human'], 'render_fps': 50}

    def __init__(self, model_path=None,
                 motor_mapping_path=DEFAULT_MOTOR_MAPPING_PATH,
                 render_mode=None, domain_randomization=False, task='stand',
                 walk_start_pose='standing', walk_height_fraction=WALK_HEIGHT_FRACTION,
                 control_mode='position', position_kp=None, position_kd=None,
                 position_kp_range=None, position_kd_range=None):
        super().__init__()
        if task not in ('stand', 'walk'):
            raise ValueError(f"task must be 'stand' or 'walk', got {task!r}")
        # 'position' (default, unchanged): <position> PD actuators, action =
        # target joint angle -- matches real hardware's only control mode
        # (actuator package exposes position/velocity services, no torque
        # command yet). 'torque' (2026-08-03, user request): <motor>
        # actuators, action = raw joint torque -- SIM-ONLY, for comparing
        # training behavior against the position-controlled setup; not
        # deployable to real hardware as-is. See DEFAULT_TORQUE_MODEL_PATH,
        # the action_space branch below, and step()'s control_mode branch.
        # 'torque_belt' (2026-08-05, user request -- see daniel_cl_context.md
        # TODO 4's refinement): same torque action space as 'torque', but
        # the calf motors additionally get an automatic, NON-learned servo
        # torque added on top of the policy's own torque -- see step()'s
        # BELT_SERVO_GAIN block. Motivated by a real "stiff-legged" gait
        # found under plain 'torque' mode (calf range of motion 16-38deg
        # vs the thigh's 84-95deg, walk_policy_torque_v8 @7M): plain
        # 'torque' has NO belt-compensation at all on the action side
        # (unlike 'position', see step()'s belt-compensation comment),
        # so nothing automatically cancels the "carried along" rotation
        # the real belt cancels for free -- the policy has to spend
        # learned torque effort reproducing something that costs the
        # real motor nothing, and apparently hadn't discovered how.
        # 'torque_belt' fixes that at the control-law level (not via
        # reward shaping) so the policy's own torque output on the calf
        # motors represents ONLY genuine, deliberate flexion; the thighs
        # are completely unaffected in every mode.
        if control_mode not in ('position', 'torque', 'torque_belt'):
            raise ValueError(
                f"control_mode must be 'position', 'torque', or 'torque_belt', got {control_mode!r}")
        self.control_mode = control_mode
        # A fixed gain and a randomized range are mutually exclusive --
        # see position_kp_range/position_kd_range's own comment below for
        # why they're a separate mechanism from position_kp/position_kd,
        # not a generalization of it.
        if (position_kp is not None or position_kd is not None) and \
                (position_kp_range is not None or position_kd_range is not None):
            raise ValueError(
                'Pass either position_kp/position_kd (fixed) or position_kp_range/'
                'position_kd_range (randomized per episode), not both.')
        if model_path is None:
            # torque_belt gets its OWN model file (DEFAULT_TORQUE_BELT_
            # MODEL_PATH, generate_dog_mjcf.py --actuator-type
            # torque_belt) -- it has real <fixed> tendons the plain
            # torque model doesn't, so it can't share DEFAULT_TORQUE_
            # MODEL_PATH the way an earlier (abandoned) control-law-only
            # attempt at this could.
            model_path = {
                'torque': DEFAULT_TORQUE_MODEL_PATH,
                'torque_belt': DEFAULT_TORQUE_BELT_MODEL_PATH,
            }.get(control_mode, DEFAULT_MODEL_PATH)
        # WALK-only (2026-08-03, user request: make this a CLI-tunable
        # parameter instead of a hardcoded constant). Defaults to the
        # module-level WALK_HEIGHT_FRACTION so existing calls/tests that
        # don't pass this keep behaving exactly as before. Computed as an
        # INSTANCE attribute (self._walk_target_height_m), not a module
        # global, since it can now differ per-env-instance -- see
        # _compute_reward_walk()'s height_reward, the only place that
        # reads it.
        self._walk_target_height_m = walk_height_fraction * STAND_HEIGHT_M
        # WALK-only (2026-08-03, user request, inspired by friend_code's
        # approach of training one policy to climb from home AND walk,
        # rather than assuming a separate stand policy always runs first).
        # 'standing' is the original/default behavior -- episode starts
        # already standing (see module docstring for why: composing a
        # stand policy + a walk policy was the original plan). 'home'
        # starts from the sitting/home pose instead, same starting state
        # STAND's own task uses -- see reset()'s walk branch.
        if walk_start_pose not in ('standing', 'home'):
            raise ValueError(f"walk_start_pose must be 'standing' or 'home', got {walk_start_pose!r}")
        self.walk_start_pose = walk_start_pose
        self.task = task
        # torque_belt only -- see BELT_TARGET_ADAPT_RATE_STAND/_WALK's
        # comment for why these need different timescales. Harmless to set
        # even outside control_mode='torque_belt' (step()'s belt branch is
        # the only reader).
        self._belt_target_adapt_rate = (
            BELT_TARGET_ADAPT_RATE_WALK if task == 'walk' else BELT_TARGET_ADAPT_RATE_STAND)
        self.model_path = model_path
        self.render_mode = render_mode
        self.domain_randomization = domain_randomization

        self.model = mujoco.MjModel.from_xml_path(self.model_path)
        self.data = mujoco.MjData(self.model)

        # position_kp/position_kd (2026-08-05, user request): runtime
        # override of the MJCF's baked-in <position> actuator gains
        # (generate_dog_mjcf.py --kp/--kv, default 60/4 -- deliberately
        # matched to actuator's real position_kp/position_kd so sim
        # training and real deployment agree on stiffness). Every
        # attempt at training position-mode WALK from scratch has failed
        # even at 27-35M steps (see daniel_cl_context.md) -- the
        # hypothesis is that gain's own stiffness is part of the
        # problem: PPO's exploration noise on a target angle gets turned
        # into a large, near-instantaneous corrective force at kp=60,
        # producing violent snapping/falling rather than the graceful
        # degradation torque-mode actions get from the leg's own inertia
        # -- a harsh reward landscape for exploration to climb out of.
        # NOT baked into a separate MJCF file (unlike torque_belt's
        # DEFAULT_TORQUE_BELT_MODEL_PATH) since these are meant to be
        # swept/compared across training runs, not fixed once -- setting
        # actuator_gainprm/biasprm directly post-load is equivalent to
        # regenerating the XML with different --kp/--kv (same MuJoCo
        # <position> shortcut expansion: gainprm[0]=kp,
        # biasprm=[0,-kp,-kv]) without maintaining N near-duplicate MJCF
        # files. None (default) leaves the MJCF's own baked-in values
        # untouched -- existing calls/tests/real-hardware-matching runs
        # are unaffected.
        if control_mode == 'position' and position_kp is not None and position_kd is not None:
            self._apply_position_gains(position_kp, position_kd)
        self.position_kp = position_kp
        self.position_kd = position_kd

        # position_kp_range/position_kd_range (2026-08-06, user request --
        # domain randomization + curriculum over position_kp/position_kd,
        # not just a single fixed override): each tuple is (low, high);
        # when set, reset() below samples a FRESH kp/kd uniformly from the
        # CURRENT range every episode (not once at construction), so the
        # same training run sees a spread of servo stiffnesses instead of
        # committing to one value for its whole lifetime -- the point is
        # robustness to whatever gain the real robot turns out to need,
        # not just picking a better single number.
        #
        # The range itself is mutable post-construction via
        # set_position_gain_range() -- NOT resampled/reapplied
        # immediately when called, only on the NEXT reset() -- so a
        # training callback can WIDEN the range over the course of
        # training (e.g. start at (10,30), end at (40,80)) via
        # VecEnv.env_method(), implementing a curriculum ON TOP of the
        # randomization: early rollouts (while the policy is close to
        # random and least able to survive a stiff, unfamiliar gain) only
        # ever see the gentle end of the range; the risky, real-hardware-
        # matching stiff end only gets sampled once the policy has some
        # baseline competence. Motivated directly by measuring that
        # kp=60/kd=8 trained from scratch (no curriculum) produced a
        # policy whose raw actions genuinely varied/reversed (the
        # ctrlrange fix held) but still cost ~27% of standing height in
        # 0.14s early in a rollout (PPO_6000000_walk_position_scratch_v8)
        # -- PPO's exploration noise is a roughly fixed size in action-
        # space units, but the PHYSICAL force that noise produces scales
        # with the gain, so the same noise is far more destabilizing
        # under a near-random policy at a stiff gain than at a soft one.
        #
        # None (default, for both) leaves position_kp/position_kd (fixed
        # or MJCF-default) in sole control, matching existing behavior
        # exactly -- this is fully opt-in.
        self._position_kp_range = position_kp_range
        self._position_kd_range = position_kd_range

        self.renderer = None
        self._paused = False

        self.torso_body_id = mujoco.mj_name2id(
            self.model, mujoco.mjtObj.mjOBJ_BODY, 'torso')
        self.floor_geom_id = mujoco.mj_name2id(
            self.model, mujoco.mjtObj.mjOBJ_GEOM, 'floor')
        self.default_floor_friction = self.model.geom_friction[self.floor_geom_id].copy()

        # Each leg's collision capsule is named "<leg>_calf" (same name as
        # the calf joint, different MuJoCo namespace) and runs knee->foot
        # as ONE capsule (no separate foot geom) -- so a contact anywhere
        # along it, knee-end included, counts as "grounded" by geom alone.
        # foot_site_ids (the existing "<leg>_foot" site, already at the
        # true foot-tip position) lets contact position be compared
        # against the tip specifically, to tell "standing on the foot"
        # apart from "standing on the knee/shin" -- see
        # _foot_tip_contact_count().
        self.calf_geom_ids = [
            mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_GEOM, f'{leg}_calf')
            for leg in ('leg_a', 'leg_b', 'leg_c', 'leg_d')
        ]
        # Added 2026-08-03: a leg's THIGH touching the floor is a real,
        # distinct contact geom this project's contact-checking logic
        # previously never looked at at all (only ever checked
        # calf_geom_ids) -- see _foot_contact_state_per_leg()'s comment
        # for the case that surfaced this (a genuine thigh-floor contact,
        # confirmed via MuJoCo's own contact list, that nothing detected).
        self.thigh_geom_ids = [
            mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_GEOM, f'{leg}_thigh')
            for leg in ('leg_a', 'leg_b', 'leg_c', 'leg_d')
        ]
        self.foot_site_ids = [
            mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_SITE, f'{leg}_foot')
            for leg in ('leg_a', 'leg_b', 'leg_c', 'leg_d')
        ]

        # control_mode='torque_belt' only (2026-08-05): the 4 <fixed>
        # tendons DEFAULT_TORQUE_BELT_MODEL_PATH defines, each equal to
        # one leg's calf ABSOLUTE (belt-decoupled) angle -- see
        # generate_dog_mjcf.py's --actuator-type torque_belt for the
        # exact formula. self.data.ten_length/ten_velocity at these
        # indices give the EXACT absolute calf angle/rate, computed by
        # MuJoCo's own tendon Jacobian -- used by step()'s belt-servo
        # PD term and reset()'s per-episode reference capture. -1 for
        # every leg (harmless) if the loaded model has no tendons (any
        # other control_mode) -- never dereferenced in that case.
        self.calf_tendon_ids = [
            mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_TENDON, f'{leg}_calf_absolute')
            for leg in ('leg_a', 'leg_b', 'leg_c', 'leg_d')
        ]

        # motor_1..motor_8 -> this joint's qpos/qvel address, so the
        # observation is built in a fixed, motor-id order regardless of
        # the MJCF's body-tree traversal order.
        joint_names = load_motor_joint_names(motor_mapping_path)
        self.motor_qpos_adr = np.array(
            [self.model.joint(name).qposadr[0] for name in joint_names])
        self.motor_dof_adr = np.array(
            [self.model.joint(name).dofadr[0] for name in joint_names])

        # Belt/pulley coupling compensation (real robot confirmed
        # 2026-07-25): each leg's calf motor drives its lower pulley
        # through a timing belt to an upper pulley mounted on the
        # (non-rotating-with-the-thigh) torso/shoulder; the lower pulley
        # itself free-spins on a bearing relative to the thigh. Net
        # effect: rotating ONLY the thigh does not change the calf's real
        # orientation at all -- the belt cancels the "carried along"
        # rotation a plain serial hinge would otherwise apply. Only the
        # calf motor's own rotation changes the calf's real (torso-
        # relative, i.e. ABSOLUTE) angle. dog.mjcf.xml's calf joint is a
        # plain hinge relative to the thigh body (a normal serial elbow)
        # -- the opposite behavior. Rather than rebuild the belt/pulley
        # physically (two more bodies + a tendon per leg, real pulley
        # radii not measured), this compensates at the control/
        # observation layer: action[calf]/obs[calf] represent the same
        # ABSOLUTE angle the real motor's own encoder reports (matching
        # actuator/dog_deploy, which read/command that motor directly and
        # need no change at all -- the real hardware already behaves this
        # way natively). Only the raw ctrl sent to the MJCF's
        # thigh-relative position actuator, and the raw qpos/qvel read
        # back from it, need converting -- see step()/_get_obs(). qpos
        # itself (physical DOF, reward/contact/geometry code) is
        # completely unaffected, still the same MuJoCo tree-composed
        # hinge angle it always was.
        #
        # Sign, corrected 2026-07-25, and NOT uniform across legs: ctrl_calf
        # = action_calf + calf_belt_sign*qpos_thigh. An initial
        # from-first-principles derivation assumed a single global minus
        # sign; user caught by eye (dog_gym.manual_motor_control) that the
        # calf was visibly rotating the SAME way as the thigh instead of
        # counter-rotating. Verified with a proper metric this time (the
        # calf body's FULL 3D orientation change via the rotation-matrix
        # angle -- comparing only one axis vector, as an earlier check did,
        # silently missed rotation about that same axis, which is exactly
        # what was happening): the minus sign leaves ~48deg of real drift
        # at thigh=20deg on leg_a specifically (thigh and calf rotations
        # ADDING instead of cancelling), while plus cuts it to ~2deg
        # (matching ordinary PD droop under load). But testing all 4 legs
        # the same way showed leg_a/leg_d need PLUS while leg_b/leg_c need
        # MINUS -- flipping to a single global plus (the first fix
        # attempted) would have fixed leg_a/leg_d while breaking leg_b/
        # leg_c, which were already correct.
        #
        # calf_belt_sign is therefore computed per leg, not hardcoded,
        # from the actual loaded geometry -- robust to the CAD
        # regeneration this is about to go through (cylindrical-mate fix
        # rolling out to all 4 legs) rather than a guessed per-leg-letter
        # table that would silently go stale on the next re-export. The
        # sign only depends on whether the knee axis, expressed in the
        # thigh's own frame (rotate by the calf body's quat, which is
        # relative to its thigh parent), points the same way as the hip
        # axis (same direction -> rotations in thigh-frame ADD for a
        # fixed calf qpos, so cancelling needs MINUS) or the opposite way
        # (needs PLUS). Confirmed this closed form reproduces the
        # empirically-measured per-leg signs above exactly (see
        # daniel_cl_context.md's "flip the sign" section for the
        # verification script).
        self.calf_idx = np.array(
            [i for i, n in enumerate(joint_names) if n.endswith('_calf')])
        self.calf_thigh_idx = np.array([
            joint_names.index(joint_names[i][:-len('_calf')] + '_thigh')
            for i in self.calf_idx
        ])
        self.calf_thigh_qpos_adr = self.motor_qpos_adr[self.calf_thigh_idx]
        self.calf_thigh_dof_adr = self.motor_dof_adr[self.calf_thigh_idx]

        calf_belt_sign = []
        for i in self.calf_idx:
            calf_joint_id = self.model.joint(joint_names[i]).id
            hip_joint_id = self.model.joint(joint_names[joint_names.index(
                joint_names[i][:-len('_calf')] + '_thigh')]).id
            calf_body_id = self.model.jnt_bodyid[calf_joint_id]
            knee_axis_in_thigh_frame = np.zeros(3)
            mujoco.mju_rotVecQuat(
                knee_axis_in_thigh_frame, self.model.jnt_axis[calf_joint_id],
                self.model.body_quat[calf_body_id])
            same_direction = np.dot(knee_axis_in_thigh_frame, self.model.jnt_axis[hip_joint_id]) > 0
            calf_belt_sign.append(-1.0 if same_direction else 1.0)
        self.calf_belt_sign = np.array(calf_belt_sign)

        # WALK's residual-action baseline (see WALK_ACTION_RESIDUAL_RANGE_RAD's
        # comment) -- the ABSOLUTE, belt-compensated equivalent of
        # STANDING_QPOS_DEG (matching the SAME conversion reset() applies
        # to its own prev_action, minus reset()'s domain_randomization
        # noise -- this baseline is deliberately FIXED/noise-free, unlike
        # reset()'s prev_action, since it's the reference the policy's
        # residual output is added to every step, not a one-time initial
        # condition; a per-episode-randomized baseline would make the
        # network's learned residual behavior inconsistent across
        # episodes). Computed once here (fully static) and used by
        # step() only.
        walk_default_rad = np.radians(STANDING_QPOS_DEG).copy()
        walk_default_rad[self.calf_idx] -= (
            self.calf_belt_sign * np.radians(STANDING_QPOS_DEG)[self.calf_thigh_idx])
        self._walk_default_action_rad = walk_default_rad.astype(np.float32)

        # NOTE: for calf motors, this is the raw MJCF actuator's
        # thigh-relative ctrlrange, used as-is for the ABSOLUTE action
        # space too (see calf_idx's comment above) -- an approximation,
        # since the true reachable absolute range shifts with the
        # paired thigh's current angle. Not a safety gap: the joint's own
        # <joint range>/limited="true"> in dog.mjcf.xml is the real hard
        # clamp MuJoCo enforces regardless of what ctrl requests, this
        # box is only PPO's action-distribution bound.
        ctrlrange = self.model.actuator_ctrlrange.copy()
        if self.control_mode in ('torque', 'torque_belt'):
            # Direct torque control (see control_mode's comment in __init__)
            # -- action IS the <motor> actuator's ctrl value (torque_belt:
            # PLUS an automatic servo term added on top for calf motors
            # only, see step()), no residual baseline, no belt/pulley
            # ANGLE compensation the way 'position' has (that compensation
            # is specifically about converting a target ANGLE between
            # thigh-relative and absolute frames -- torque applied to the
            # calf's modeled hinge DOF needs no such conversion, see
            # step()'s control_mode branch), same for both tasks.
            self.action_space = spaces.Box(
                low=ctrlrange[:, 0].astype(np.float32),
                high=ctrlrange[:, 1].astype(np.float32),
                dtype=np.float32)
        elif self.task == 'walk':
            # RESIDUAL action space -- see WALK_ACTION_RESIDUAL_RANGE_RAD's
            # comment. step() converts this back to an absolute target
            # (self._walk_default_action_rad + action) before anything
            # else (slew clamp, belt compensation, reward) touches it --
            # everything downstream of that conversion is unchanged from
            # STAND's absolute-action behavior.
            self.action_space = spaces.Box(
                low=-WALK_ACTION_RESIDUAL_RANGE_RAD,
                high=WALK_ACTION_RESIDUAL_RANGE_RAD,
                shape=(NUM_MOTORS,), dtype=np.float32)
        else:
            self.action_space = spaces.Box(
                low=ctrlrange[:, 0].astype(np.float32),
                high=ctrlrange[:, 1].astype(np.float32),
                dtype=np.float32)

        self.prev_action = np.zeros(NUM_MOTORS, dtype=np.float32)
        # Per-leg (leg_a..leg_d order) seconds spent airborne since that
        # leg's last ground contact -- persistent state for
        # _feet_air_time_reward(), reset in reset() below.
        self._feet_air_time = np.zeros(4)
        # Mirror image: seconds spent PLANTED since that leg's last
        # swing -- see FEET_STANCE_TIME_MAX_S's comment.
        self._feet_stance_time = np.zeros(4)
        # Per-leg seconds spent in CONTINUOUS non-tip (knee/shin) contact
        # -- see NONTIP_TERMINATION_S's comment / _knee_walking_too_long().
        self._non_tip_contact_time = np.zeros(4)
        # Per-leg seconds spent in CONTINUOUS full airborne (no contact at
        # all) -- see STAND_AIRBORNE_TERMINATION_S's comment /
        # _not_all_feet_grounded().
        self._airborne_time = np.zeros(4)
        # STAND push perturbation state -- see STAND_PUSH_PROB_PER_STEP's
        # comment. _push_remaining_s counts down while a push is active;
        # _push_force is the fixed force vector applied for that
        # duration once triggered.
        self._push_remaining_s = 0.0
        self._push_force = np.zeros(3)
        # Per-leg seconds since that leg's contact state (grounded vs
        # swinging) last CHANGED, either direction -- see MAX_LEG_PHASE_S's
        # comment / _trot_symmetry_reward()'s stuck-phase gate.
        self._leg_phase_time = np.zeros(4)
        self._prev_leg_contact = np.zeros(4, dtype=bool)
        # Seconds torso pitch magnitude has stayed continuously above
        # PITCH_TERMINATION_THRESHOLD_RAD -- see that constant's comment
        # / _pitch_diverging_too_long().
        self._high_pitch_time = 0.0
        # World +y torso position at episode start -- see
        # NO_PROGRESS_GRACE_S's comment / _no_forward_progress(). Real
        # value set at the end of reset() below, once this episode's
        # starting pose is finalized; 0.0 here is just a placeholder.
        self._episode_start_y = 0.0

        # motor qpos (8) + motor qvel (8) + IMU sensordata + prev_action (8)
        self.single_obs_dim = NUM_MOTORS + NUM_MOTORS + self.model.nsensordata + NUM_MOTORS
        self.obs_history_len = 3
        obs_dim = self.single_obs_dim * self.obs_history_len
        self.observation_space = spaces.Box(
            low=-np.inf, high=np.inf, shape=(obs_dim,), dtype=np.float32)
        self._obs_history = np.zeros(obs_dim, dtype=np.float32)

        self._step_count = 0

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)

        mujoco.mj_resetData(self.model, self.data)
        self.prev_action = np.zeros(NUM_MOTORS, dtype=np.float32)
        self._feet_air_time = np.zeros(4)
        self._feet_stance_time = np.zeros(4)
        self._non_tip_contact_time = np.zeros(4)
        self._airborne_time = np.zeros(4)
        # STAND push perturbation state -- see STAND_PUSH_PROB_PER_STEP's
        # comment. _push_remaining_s counts down while a push is active;
        # _push_force is the fixed force vector applied for that
        # duration once triggered.
        self._push_remaining_s = 0.0
        self._push_force = np.zeros(3)
        self._leg_phase_time = np.zeros(4)
        self._prev_leg_contact = np.zeros(4, dtype=bool)
        self._high_pitch_time = 0.0
        self._step_count = 0

        if self.task == 'walk':
            if self.walk_start_pose == 'standing':
                # Start already standing -- see module docstring: composing
                # a stand policy + a walk policy is the plan, not one
                # policy learning to stand up and walk forward at once.
                qpos_rad = np.radians(STANDING_QPOS_DEG)
            else:
                # 'home' (2026-08-03, user request): start from the
                # sitting/home pose instead, same starting state STAND's
                # task uses -- mj_resetData already leaves motor qpos at
                # the model's default 0 for this, nothing to set here. One
                # policy now has to climb to standing height AND walk
                # forward, rather than assuming a separate stand policy
                # always runs first.
                qpos_rad = np.zeros(NUM_MOTORS)
            if self.domain_randomization:
                qpos_rad = qpos_rad + self.np_random.uniform(-0.02, 0.02, size=NUM_MOTORS)
            self.data.qpos[self.motor_qpos_adr] = qpos_rad
            # step()'s slew-rate limiter clips each new action around
            # prev_action -- leaving prev_action at its zero default here
            # while the legs are actually at the standing pose would make
            # the very first step() think the last commanded target was 0
            # and yank every leg toward 0 (rate-limited, so a slow fake
            # "collapse" rather than an instant snap, but still wrong).
            # prev_action lives in the policy's ABSOLUTE action space (see
            # calf_idx's comment in __init__), so the calf entries of this
            # raw (thigh-relative) qpos snapshot need the same
            # qpos[calf]-qpos[paired thigh] conversion _get_obs() uses.
            # This formula is agnostic to which branch above set qpos_rad,
            # so it's correct for either start pose.
            #
            # control_mode='torque'/'torque_belt' (2026-08-03/05): none of
            # this applies -- there's no slew clamp and no meaningful
            # "last commanded angle" in torque units, so prev_action stays
            # at reset()'s zero default (no torque commanded yet)
            # regardless of the legs' actual starting pose. Guard below is
            # inverted (only 'position' overrides) so both torque modes
            # correctly fall through without needing their own branch.
            if self.control_mode == 'position':
                prev_action = qpos_rad.copy()
                prev_action[self.calf_idx] -= self.calf_belt_sign * qpos_rad[self.calf_thigh_idx]
                self.prev_action = prev_action.astype(np.float32)
            if self.walk_start_pose == 'standing':
                # The free joint's own z (qpos[2]) still defaults to the
                # model's qpos=0 spawn height (0.287m, chosen to clear the
                # floor at the CAD-captured/sitting leg pose) -- leaving it
                # there while the legs are suddenly snapped to the standing
                # pose drives the feet deep through the floor on the very
                # first physics step (extended legs + unchanged torso height
                # = feet well below z=0), producing a violent contact impulse
                # that was observed to tip the robot over and leave it stuck
                # in a partial, off-balance crouch instead of standing
                # (verified: torso settled around 0.19m tilted ~16deg, not
                # 0.277m level, regardless of how far the commanded target
                # was pushed beyond the real standing angles -- confirms the
                # cause was the initial impact, not insufficient PD gain).
                # Starting at the real settled standing height directly
                # avoids that transient.
                self.data.qpos[2] = STAND_HEIGHT_M
            else:
                # 'home' -- FIXED 2026-08-06 (user report: a walk policy's
                # very first ~16 ticks were pure free-fall, all 4 feet
                # 'air', height dropping smoothly 0.287->~0.15m with ZERO
                # ground contact the whole time, before the policy had any
                # physical grounding to act from -- "unravels its legs to
                # try and catch itself before it even hits the floor").
                # The comment this replaced claimed the qpos=0 default
                # spawn height (0.287m) was "already the physically
                # correct one" for this pose -- that was simply wrong,
                # contradicted directly by the measured free-fall above.
                # qpos_rad here is the IDENTICAL zero-motor-angle
                # configuration STAND's own branch below uses (mj_resetData's
                # default), so the SAME empirically-measured settled height
                # applies -- SIT_HEIGHT_M was measured (see STAND branch's
                # own comment) by letting the robot settle under zero torque
                # from this exact pose and reading back where it landed
                # (0.1403m, all 4 feet in clean tip contact), not derived
                # from anything STAND-specific. Reusing it here removes the
                # free-fall entirely instead of requiring the policy to
                # survive falling through it while already being scored/
                # trained on its actions.
                self.data.qpos[2] = SIT_HEIGHT_M
        elif self.task == 'stand':
            # FIXED 2026-08-04 (user question: "this is a policy to stand
            # up from a sitting position ON THE GROUND, will this still
            # work?"): motor qpos is already 0 (mj_resetData's default),
            # but the free joint's z (qpos[2]) was previously left at the
            # model's raw qpos=0 spawn height (0.287m, chosen only to
            # clear the floor at the CAD pose, not the real settled
            # height) -- meaning every STAND episode ever trained started
            # AIRBORNE, with legs curled and nothing touching the ground,
            # then fell for ~10 steps before any foot made contact. That
            # never matches how a real robot actually starts (already
            # resting on the ground, weight already supported, feet
            # already in contact). Verified directly: letting the robot
            # settle under zero torque from the old spawn reaches
            # height=0.1403m with all 4 feet in clean tip contact --
            # matches SIT_HEIGHT_M (0.14) almost exactly, and a direct
            # qpos[2]=SIT_HEIGHT_M assignment (no settling simulation
            # needed) reproduces that same state (up_z=1.0, all 4 tip
            # contacts, contact penetration depths of a few mm -- normal
            # soft-contact overlap, not an invalid configuration).
            # Cheaper than re-running a settling simulation every reset,
            # since it's just the already-measured constant.
            self.data.qpos[2] = SIT_HEIGHT_M

        if self.domain_randomization:
            self._randomize_ground()
        else:
            self.model.geom_friction[self.floor_geom_id] = self.default_floor_friction

        # position_kp_range/position_kd_range (see __init__'s comment):
        # fresh sample every episode from whatever the CURRENT range
        # bounds are (may have been widened since the last episode by a
        # training callback via set_position_gain_range()). Independent
        # of self.domain_randomization -- that flag only ever gated
        # ground friction; gain randomization is opt-in purely by
        # whether a range was passed at all.
        if self._position_kp_range is not None:
            kp = self.np_random.uniform(*self._position_kp_range)
            kd = self.np_random.uniform(*self._position_kd_range)
            self._apply_position_gains(kp, kd)
            self.position_kp = kp
            self.position_kd = kd

        mujoco.mj_forward(self.model, self.data)

        # control_mode='torque_belt' only: seed this episode's belt-servo
        # reference (per leg) at the starting pose -- see BELT_SERVO_KP's
        # comment for why the starting pose and not a hardcoded constant.
        # ADAPTIVE since 2026-08-05 (BELT_TARGET_ADAPT_RATE) -- this is
        # only the INITIAL value now, step() leaky-integrates it toward
        # wherever the calf actually is every tick after this, so it
        # stops fighting a sustained, deliberate pose change (like
        # standing up) partway through the episode instead of holding
        # this reset-time value fixed for the whole thing. Read AFTER
        # mj_forward above so self.data.ten_length reflects the qpos
        # this reset() call actually just set, not stale data from the
        # previous episode.
        if self.control_mode == 'torque_belt':
            self._belt_target_abs_calf = self.data.ten_length[self.calf_tendon_ids].copy()

        # See NO_PROGRESS_GRACE_S's comment / _no_forward_progress() --
        # read AFTER mj_forward above, same reasoning as
        # _belt_target_abs_calf's own comment.
        self._episode_start_y = self.data.xpos[self.torso_body_id][1]

        # Populate initial history (copy the first obs to all history slots)
        initial_obs = self._get_obs()
        for i in range(self.obs_history_len):
            self._obs_history[i * self.single_obs_dim : (i + 1) * self.single_obs_dim] = initial_obs

        return self._obs_history.copy(), {}

    def _randomize_ground(self):
        friction = self.np_random.uniform(0.3, 0.8)
        self.model.geom_friction[self.floor_geom_id] = [friction, friction * 0.1, friction * 0.1]

    def _apply_position_gains(self, kp, kd):
        """Writes kp/kd directly into the loaded model's <position>
        actuator gain/bias params -- same MuJoCo <position> shortcut
        expansion generate_dog_mjcf.py's --kp/--kv produce at compile
        time (gainprm[0]=kp, biasprm=[0,-kp,-kv]), just applied at
        runtime so kp/kd can be swept/randomized/curriculum-scheduled
        across training without maintaining separate MJCF files per
        value. Shared by __init__'s one-time fixed override and reset()'s
        per-episode randomized sample -- see position_kp_range's comment
        in __init__ for why there are two separate mechanisms."""
        self.model.actuator_gainprm[:, 0] = kp
        self.model.actuator_biasprm[:, 1] = -kp
        self.model.actuator_biasprm[:, 2] = -kd

    def set_position_gain_range(self, kp_range, kd_range):
        """Updates the (low, high) bounds reset() samples position_kp/
        position_kd from on the NEXT episode -- does NOT resample or
        reapply gains to the CURRENT episode immediately (changing
        actuator stiffness mid-episode would be a discontinuity the
        policy never trained for). Meant to be called externally via
        VecEnv.env_method() from a training callback implementing a
        curriculum over the randomization range -- see
        position_kp_range's comment in __init__ for the full reasoning
        and train.py's GainRangeCurriculumCallback for the schedule
        itself."""
        self._position_kp_range = kp_range
        self._position_kd_range = kd_range

    def step(self, action):
        action = np.clip(action, self.action_space.low, self.action_space.high)
        if self.control_mode == 'torque':
            # Direct torque control (2026-08-03, sim-only comparison --
            # see control_mode's comment in __init__): action IS the
            # <motor> actuator's ctrl value, already clipped to
            # ctrlrange above. None of the position-control machinery
            # below applies -- no residual->absolute conversion (no
            # baseline pose to be a residual around), no slew-rate clamp
            # (that's specifically a real-hardware POSITION-command
            # safety limit, dog_deploy/policy_node.py has no torque path
            # to match), no belt/pulley angle compensation (that's for
            # converting a target ANGLE between thigh-relative and
            # absolute frames -- torque applied straight to the calf's
            # modeled hinge DOF needs no such conversion).
            #
            # Velocity damping ADDED 2026-08-04 (see TORQUE_KD_GAIN's
            # comment) -- matches actuator's real set_motor_torque
            # service, which now applies the same brake via the
            # firmware's cmd.kd, transparently to the policy. Applied
            # here (not left for the policy to learn on its own) so
            # training experiences the SAME closed-loop dynamics real
            # deployment will actually have.
            self.data.ctrl[:] = action - TORQUE_KD_GAIN * self.data.qvel[self.motor_dof_adr]
        elif self.control_mode == 'torque_belt':
            # Same base torque + damping as 'torque' above (thighs
            # completely untouched), PLUS an automatic, NON-learned
            # belt-compensation PD servo added to the calf motors only --
            # see control_mode's comment in __init__, BELT_SERVO_KP's
            # comment, and daniel_cl_context.md's TODO 4 refinement for
            # the full history.
            #
            # HISTORY (why this isn't the raw-joint velocity-servo the
            # first attempt used): applying a correction directly to the
            # calf's raw (thigh-relative) DOF measured needing 80-110
            # N*m to track the required velocity -- it was fighting the
            # SAME shared, saturating +-20 N*m torque budget as
            # everything else on that actuator. DEFAULT_TORQUE_BELT_
            # MODEL_PATH's calf actuators now target a <fixed> tendon
            # (generate_dog_mjcf.py --actuator-type torque_belt) equal to
            # the calf's ABSOLUTE angle directly -- MuJoCo's constraint
            # solver distributes the resulting force back to the raw
            # joints EXACTLY, no competing-force/saturation problem by
            # construction. Verified directly: the same PD gains held
            # within ~10deg of target against sustained thigh torque,
            # needing at most ~10 N*m -- comfortably inside budget.
            #
            # self.data.ten_length/ten_velocity at self.calf_tendon_ids
            # ARE the calf's exact absolute angle/rate (computed by
            # MuJoCo itself, not manually re-derived) -- target is
            # self._belt_target_abs_calf (captured once per episode in
            # reset(), see BELT_SERVO_KP's comment for why that reference
            # and not a hardcoded constant). Added ON TOP of the policy's
            # own calf torque (action[calf_idx]), not replacing it --
            # after this, the policy's calf output represents ONLY
            # genuine, deliberate flexion beyond whatever the automatic
            # tracking already provides for free.
            ctrl = action - TORQUE_KD_GAIN * self.data.qvel[self.motor_dof_adr]
            abs_calf = self.data.ten_length[self.calf_tendon_ids]
            abs_calf_vel = self.data.ten_velocity[self.calf_tendon_ids]
            # ADAPTIVE target (2026-08-05, see BELT_TARGET_ADAPT_RATE_STAND/
            # _WALK's comment) -- leaky-integrates toward the CURRENT
            # absolute calf angle every tick, BEFORE this tick's P term is
            # computed, so a sustained pose change (standing up) or a
            # normal gait swing (walking) isn't fought for the whole
            # episode/stride, only during genuinely fast transients.
            # self._belt_target_adapt_rate is task-dependent, set in
            # __init__.
            self._belt_target_abs_calf += self._belt_target_adapt_rate * (abs_calf - self._belt_target_abs_calf)
            belt_pd = (BELT_SERVO_KP * (self._belt_target_abs_calf - abs_calf)
                       + BELT_SERVO_KD * (0.0 - abs_calf_vel))
            ctrl[self.calf_idx] += belt_pd
            # REACTION CANCELLATION (2026-08-05, found on walk_home_torque_belt
            # @16M): the <fixed> tendon combines BOTH the calf and thigh
            # joints (coef=[1, -calf_belt_sign], see generate_dog_mjcf.py),
            # so MuJoCo distributes belt_pd back to the THIGH too, not just
            # the calf -- an unintended, policy-uncontrolled torque
            # leaking onto the thigh every tick. Measured directly: on the
            # two legs with the smallest thigh swing (10-16deg range), this
            # leaked reaction (2.6-2.8 N*m mean) was actually LARGER than
            # the policy's own deliberate thigh torque (1.7-2.5 N*m) --
            # the thigh was spending more effort fighting the calf servo's
            # disturbance than doing anything the policy intended, which
            # is exactly why those thighs weren't swinging: it directly
            # broke the "thighs are completely unaffected" design goal
            # every other control_mode branch maintains. Cancelled by
            # adding the exact opposite of the tendon's own thigh
            # coefficient (-calf_belt_sign) to that thigh's OWN separate
            # (non-tendon) actuator -- net effect on the thigh DOF is now
            # back to just ctrl[thigh] (from the base torque+damping line
            # above), same as plain 'torque' mode; only the calf still
            # feels belt_pd.
            ctrl[self.calf_thigh_idx] += self.calf_belt_sign * belt_pd
            self.data.ctrl[:] = ctrl
        else:
            if self.task == 'walk':
                # RESIDUAL -> ABSOLUTE conversion (see
                # WALK_ACTION_RESIDUAL_RANGE_RAD's comment) -- action was just
                # clipped to the residual range above; convert it to the same
                # absolute-angle terms STAND's action always was, BEFORE any
                # of the logic below (slew clamp, belt compensation, reward
                # computation) touches it. Everything downstream is completely
                # unchanged from the pre-residual behavior -- prev_action,
                # ctrl, and every reward term still operate on absolute
                # angles exactly as before.
                action = self._walk_default_action_rad + action
            # Rate-limit how far any single motor's target can move per step,
            # same idea (and same underlying number) as dog_deploy/policy_node.py's
            # real-hardware safety clamp: that clamps 5deg per 20Hz control tick
            # = 100deg/s. Sim steps at 100Hz (dog.mjcf.xml's 0.01s timestep, one
            # physics step per env.step(), no frame-skip), so the equivalent
            # per-sim-step limit is 100deg/s / 100Hz = 1deg/step -- same overall
            # speed limit, just expressed at the sim's own step rate. Without
            # this, a policy is free to snap straight to any target every step
            # (visibly "stands up too fast"), which also doesn't reflect what
            # the real, rate-limited deployment path will actually allow --
            # training under the same limit avoids that train/deploy mismatch.
            max_delta_rad = np.radians(MAX_SLEW_DEG_PER_S) * self.model.opt.timestep
            action = np.clip(action, self.prev_action - max_delta_rad, self.prev_action + max_delta_rad)

            # Belt/pulley compensation (see calf_idx's comment in __init__,
            # including the sign note): action[calf] is an ABSOLUTE angle;
            # dog.mjcf.xml's calf actuator servos a thigh-RELATIVE hinge, so
            # ADD the thigh's current angle before writing ctrl. Thigh entries
            # (and any non-calf motor) pass through unchanged.
            ctrl = action.copy()
            ctrl[self.calf_idx] = action[self.calf_idx] + self.calf_belt_sign * self.data.qpos[self.calf_thigh_qpos_adr]
            self.data.ctrl[:] = ctrl

        # STAND push perturbation (see STAND_PUSH_PROB_PER_STEP's
        # comment) -- applied every tick right before mj_step, same
        # pattern as ctrl above, so this tick's physics integration
        # actually feels it. A push in progress keeps the SAME force
        # vector applied for STAND_PUSH_DURATION_S; once it lapses, a
        # fresh coin flip may start a new one in a new random direction.
        if self.task == 'stand' and self.domain_randomization:
            dt = self.model.opt.timestep
            if self._push_remaining_s <= 0.0 and self.np_random.uniform() < STAND_PUSH_PROB_PER_STEP:
                angle = self.np_random.uniform(0.0, 2 * np.pi)
                magnitude = self.np_random.uniform(*STAND_PUSH_FORCE_RANGE_N)
                self._push_force = np.array(
                    [magnitude * np.cos(angle), magnitude * np.sin(angle), 0.0])
                self._push_remaining_s = STAND_PUSH_DURATION_S
            if self._push_remaining_s > 0.0:
                self.data.xfrc_applied[self.torso_body_id, 0:3] = self._push_force
                self._push_remaining_s -= dt
            else:
                self.data.xfrc_applied[self.torso_body_id, 0:3] = 0.0
        elif self.data.xfrc_applied[self.torso_body_id].any():
            # Task/mode switched or domain_randomization turned off
            # mid-episode (shouldn't normally happen, but don't leave a
            # stale push force applied forever if it does).
            self.data.xfrc_applied[self.torso_body_id, :] = 0.0

        if self.render_mode == 'human':
            self._ensure_viewer()
            # Space bar toggles self._paused via _on_key. mj_step only
            # advances while unpaused; the viewer keeps redrawing (and
            # stays responsive to mouse/keyboard) either way.
            while self._paused and self.renderer.is_running():
                self.renderer.sync()
                time.sleep(0.02)

        mujoco.mj_step(self.model, self.data)
        self._step_count += 1
        # MUST update before _compute_reward() -- _trot_symmetry_reward()
        # reads self._leg_phase_time and needs this tick's transition
        # already reflected. See _update_leg_phase_time()'s docstring.
        self._update_leg_phase_time()
        self._update_high_pitch_time()

        reward = self._compute_reward(action)

        self.prev_action = action.astype(np.float32)

        current_obs = self._get_obs()
        self._obs_history[:-self.single_obs_dim] = self._obs_history[self.single_obs_dim:]
        self._obs_history[-self.single_obs_dim:] = current_obs
        obs = self._obs_history.copy()
        
        # MUST update before checking _knee_walking_too_long() -- see that
        # method's docstring.
        self._update_nontip_contact_time()
        # MUST update before checking _not_all_feet_grounded() -- same
        # reasoning, see _update_airborne_time()'s docstring.
        self._update_airborne_time()
        # The three checks after _knee_walking_too_long() are additional
        # WALK-only early terminations (2026-08-05, user request) --
        # see LEG_PHASE_TERMINATION_S/PITCH_TERMINATION_THRESHOLD_RAD/
        # NO_PROGRESS_GRACE_S's comments. All three no-op (False) for
        # STAND.
        #
        # Split out as fell_over vs. terminated (2026-08-06) so
        # WALK_FALL_TERMINAL_PENALTY below can target real falls/
        # instability specifically -- _no_forward_progress() is "gave up
        # without moving," a different failure mode from an actual fall,
        # and deliberately excluded from the penalty (see that
        # constant's comment).
        fell_over = (self._is_fallen() or self._knee_walking_too_long()
                     or self._leg_stuck_too_long() or self._pitch_diverging_too_long()
                     or self._not_all_feet_grounded())
        terminated = fell_over or self._no_forward_progress()
        truncated = self._step_count >= MAX_EPISODE_STEPS

        if self.task == 'walk' and fell_over:
            reward += WALK_FALL_TERMINAL_PENALTY

        if self.render_mode == 'human':
            self.render()

        return obs, reward, terminated, truncated, {}

    def _get_obs(self):
        # Belt/pulley compensation (see calf_idx's comment in __init__):
        # convert the calf hinge's raw, thigh-relative qpos/qvel into the
        # ABSOLUTE angle/rate the real motor's own encoder would report,
        # so the policy's observation matches actuator/dog_deploy's
        # read_motor_positions on real hardware with no further change
        # needed there.
        motor_qpos = self.data.qpos[self.motor_qpos_adr].copy()
        motor_qvel = self.data.qvel[self.motor_dof_adr].copy()
        motor_qpos[self.calf_idx] -= self.calf_belt_sign * self.data.qpos[self.calf_thigh_qpos_adr]
        motor_qvel[self.calf_idx] -= self.calf_belt_sign * self.data.qvel[self.calf_thigh_dof_adr]
        sensordata = self.data.sensordata

        # SENSOR NOISE (2026-07-27, opt-in via domain_randomization):
        # real-hardware deployment of a "converged"-looking stand policy
        # showed persistent chatter at a settled stand pose, traced
        # directly to the raw policy action itself being unstable at
        # steady state (see action_rate_penalty's comment in
        # _common_penalties()) -- sim's observation had ALWAYS been
        # perfectly noise-free, unlike anything the real robot's
        # encoders/IMU actually report, so a policy never has any reason
        # to learn robustness to small measurement noise on its own.
        # Added here so training can optionally include that noise (see
        # MOTOR_POS_NOISE_STD_RAD's comment for magnitudes/placeholder
        # status). NOT applied to prev_action -- that's the policy's own
        # last commanded value, not a sensor reading, and stays exact on
        # both sim and real (dog_deploy/policy_node.py's prev_action is
        # likewise the exact last clamped command, never a measurement).
        if self.domain_randomization:
            motor_qpos = motor_qpos + self.np_random.normal(
                0.0, MOTOR_POS_NOISE_STD_RAD, size=NUM_MOTORS)
            motor_qvel = motor_qvel + self.np_random.normal(
                0.0, MOTOR_VEL_NOISE_STD_RAD_S, size=NUM_MOTORS)
            sensordata = sensordata.copy()
            sensordata[0:3] += self.np_random.normal(0.0, ACCEL_NOISE_STD_M_S2, size=3)
            sensordata[3:6] += self.np_random.normal(0.0, GYRO_NOISE_STD_RAD_S, size=3)

        return np.concatenate([
            motor_qpos,
            motor_qvel,
            sensordata,
            self.prev_action,
        ]).astype(np.float32)

    def _torso_height(self):
        return self.data.xpos[self.torso_body_id][2]

    def _torso_up_z(self):
        """World-frame z-component of the torso's local up axis: 1.0 =
        perfectly upright, drops towards 0 as the robot tips over."""
        xmat = self.data.xmat[self.torso_body_id].reshape(3, 3)
        return xmat[2, 2]

    def _torso_pitch_rad(self):
        """Forward/backward tilt (radians): 0 = level, positive = nose-
        down (pitching forward). World-z component of the torso's local
        FORWARD (y) axis -- see _torso_up_z()'s comment for the xmat
        layout convention (columns = local axes in world coords).

        Added 2026-07-30 alongside WALK_PITCH_PENALTY_WEIGHT: up_z alone
        is a poor signal for THIS specific failure mode -- it's a cosine
        of the tilt angle, which is very flat near 0 (a 15deg lean only
        costs 1-cos(15deg)=0.034 out of a 1.0 max), so upright_reward
        barely registers a sustained forward lean as long as the robot
        doesn't fully tip over. This gives a direct, much more sensitive
        signal for exactly that lean (verified: PPO_18000000_
        walk_policy_v6 measured 12.9deg mean forward pitch, barely
        improving over 6M-18M of training, while wobble improved
        substantially over the same span -- a real, still-uncorrected
        gap up_z's insensitivity was masking)."""
        xmat = self.data.xmat[self.torso_body_id].reshape(3, 3)
        return np.arcsin(np.clip(-xmat[2, 1], -1.0, 1.0))

    def _num_feet_grounded(self):
        """How many of the 4 calf capsules are in actual contact with the
        floor geom right now (0-4) -- a real physical ground-contact
        check via MuJoCo's own contact list, not a height-based guess.
        Doesn't distinguish WHERE on the capsule contact happens (knee
        end counts the same as the foot tip) -- see
        _foot_tip_contact_count() for that."""
        grounded = set()
        for i in range(self.data.ncon):
            c = self.data.contact[i]
            if c.geom1 == self.floor_geom_id and c.geom2 in self.calf_geom_ids:
                grounded.add(c.geom2)
            elif c.geom2 == self.floor_geom_id and c.geom1 in self.calf_geom_ids:
                grounded.add(c.geom1)
        return len(grounded)

    def _foot_contact_per_leg(self):
        """[bool x4] (leg_a, leg_b, leg_c, leg_d order, matching
        calf_geom_ids/foot_site_ids): True if that leg has ANY floor
        contact right now (tip, knee/shin, OR thigh -- see
        _foot_contact_state_per_leg()), False if fully airborne
        (mid-swing). Used by _foot_clearance_reward() to know which legs
        should be judged on swing height vs. which are legitimately
        planted."""
        return [state != 'air' for state in self._foot_contact_state_per_leg()]

    def _trot_symmetry_reward(self):
        """Rewards a diagonal-pair TROT contact pattern -- leg_a (front-
        right) + leg_d (back-left) sharing the same contact state
        (both grounded or both swinging together), leg_b (front-left) +
        leg_c (back-right) likewise, and the two diagonal PAIRS offset
        from each other (one pair grounded while the other swings) --
        the standard, most efficient quadruped gait at moderate speed,
        matching how real dogs/horses trot.

        Added 2026-08-01 (TODO, user's diagonal-pairing idea) after
        repeated evidence across walk_policy_v8/v9/v10 that closing the
        "two legs do all the work, two stay planted" shortcut (see
        FEET_STANCE_TIME_MAX_S) wasn't enough on its own: every
        checkpoint kept rediscovering a DIFFERENT 2-leg-dominant
        shortcut (a/d dominant, then b/c, then back) rather than genuine
        4-leg coordination, because forcing all 4 legs to move doesn't
        by itself teach a WORKING coordination pattern -- nothing
        previously told the policy what a good one looks like. This is
        that missing piece: a direct, concrete signal for how 4 legs
        should coordinate, not just that they should all eventually
        move.

        Returns a value in [-1, 1]: 1.0 = perfect trot contact pattern
        this tick, -1.0 = the worst possible (both pairs desynced AND
        the two pairs in phase instead of offset).

        STUCK-PHASE GATE (2026-08-05, see MAX_LEG_PHASE_S's comment): if
        any leg has held its CURRENT contact state (grounded or
        swinging) for longer than MAX_LEG_PHASE_S, returns -1.0
        unconditionally instead of scoring the instantaneous pattern.
        Closes a real exploit found on walk_position_scratch_v1/
        walk_position_imitation_v1 -- this check used to be purely
        instantaneous (which 4 legs are up/down THIS tick), so a single
        non-reciprocating thigh sweep (one diagonal pair lifts once and
        never plants again) scored a sustained PERFECT 1.0 for 100+
        ticks, since nothing required the pattern to ever alternate."""
        if np.any(self._leg_phase_time > MAX_LEG_PHASE_S):
            return -1.0
        a, b, c, d = self._foot_contact_per_leg()
        pair_ad_synced = 1.0 if a == d else -1.0
        pair_bc_synced = 1.0 if b == c else -1.0
        pairs_offset = 1.0 if a != b else -1.0
        return (pair_ad_synced + pair_bc_synced + pairs_offset) / 3.0

    def _foot_clearance_reward(self):
        """Rewards a SWINGING (non-contacting) foot for actually being
        elevated, not dragged along the ground -- adapted from the
        standard feet_air_time/foot_clearance pattern used in quadruped
        locomotion RL (e.g. legged_gym/ANYmal-style reward suites).

        Why this is needed on top of _foot_placement_terms(): that reward
        only judges WHERE contact happens when it happens (tip vs.
        knee/shin) -- it says nothing about whether the leg ever lifts at
        all. A policy that drags the true foot tip along the ground
        continuously, never swinging, would score perfectly on tip-
        contact while still never producing a real walking gait -- which
        can look a lot like "walking on its knees" even with tip contact
        technically satisfied. This term specifically rewards legs that
        ARE mid-swing for being off the ground, closing that gap.

        Returns a value in [0, 1]: 1.0 means every currently-swinging leg
        is at or above FOOT_CLEARANCE_TARGET_M; legs currently in contact
        don't count either way (this isn't a "lift all feet" reward, only
        a "when swinging, actually swing" one).

        BUG FIXED 2026-07-29: the "no leg swinging" fallback used to
        return 1.0 (the MAXIMUM possible score) -- fine for a hypothetical
        stand-task caller (nothing SHOULD swing while standing still,
        that's genuinely perfect), but this method is only ever actually
        called from _compute_reward_walk(), where "no leg swinging" means
        every foot is planted and dragging continuously -- exactly the
        failure the user reported (PPO_16000000_walk_policy_v2: 0.0-0.3%
        airborne time across all 4 legs, ZERO landing events in a 1000-
        step rollout, yet this method scored 0.9957 mean / 1.0 max --
        near-perfect reward for never lifting a single leg). Changed to
        0.0 (neutral) -- no leg swinging is no longer secretly the best
        possible outcome.

        REFORMULATED 2026-08-06 (multi-agent review with Gemini's
        Antigravity CLI, see chatbot.md): the OLD per-leg formula was a
        linear ramp from 0 at foot_z=0 up to 1.0 at FOOT_CLEARANCE_
        TARGET_M, then CAPPED at 1.0 for anything higher -- a foot lifted
        0.2m scored identically to one at the 0.03m target, so it never
        penalized over-jumping. That's exactly why this term was weighted
        0.0 in the WALK return statement rather than fixed outright (see
        that return statement's own history comment) -- when the actual
        observed problem was excessive height (~0.2m), this formula had
        no lever to push back with. But leaving it at 0.0 also meant
        legs that never lift AT ALL get no dense per-tick signal telling
        them lifting is good, which is a separate, worse problem once a
        policy isn't lifting its legs at all. Now a Gaussian centered
        AT the target (sigma=FOOT_CLEARANCE_TARGET_M) penalizes
        deviation in EITHER direction -- both dragging (foot_z=0) and
        over-jumping (foot_z=0.2, ~5.7 sigma away) score low, only
        genuine near-target-height swings score close to 1.0."""
        contacted = self._foot_contact_per_leg()
        swinging = [not c for c in contacted]
        if not any(swinging):
            return 0.0  # no leg is swinging right now -- neutral, NOT rewarded (see bug note above)
        total = 0.0
        sigma = FOOT_CLEARANCE_TARGET_M
        for i, site_id in enumerate(self.foot_site_ids):
            if swinging[i]:
                foot_z = max(self.data.site_xpos[site_id][2], 0.0)
                total += float(np.exp(-((foot_z - FOOT_CLEARANCE_TARGET_M) ** 2) / (2 * sigma ** 2)))
        return total / sum(swinging)

    def _calf_swing_motion_reward(self):
        """Rewards a SWINGING leg's calf (knee) for actively moving, not
        staying near-fixed while the thigh does all the work of the
        swing. Added 2026-08-04 after measuring a real "stiff-legged"
        gait on walk_policy_torque_v8 @7M: calf range of motion 16-38deg
        across an episode vs. the thigh's 84-95deg over the SAME episode
        -- the hip was swinging the whole leg through a wide arc while
        the knee barely bent, unlike a natural bent-knee stride. Nothing
        previously rewarded calf motion specifically -- foot_clearance_
        reward only cares about the FOOT ending up elevated, however
        that's achieved (a stiff pendulum swing satisfies it just as
        well as a bent-knee one), so it never pushed toward this
        specifically.

        Uses the RAW (thigh-relative) calf qvel -- the actual physical
        knee-flexion rate -- not the belt-compensated ABSOLUTE value
        _get_obs() builds for the observation, since that conflates the
        thigh's own motion with the calf's own (a calf held perfectly
        rigid relative to the thigh still shows nonzero ABSOLUTE
        velocity whenever the thigh moves, which would reward the exact
        stiff-legged pattern this term is meant to discourage).

        Returns mean squared calf angular velocity (rad/s)^2 across
        currently-swinging legs, 0.0 if none are swinging (neutral, not
        rewarded -- same "no swinging leg keeps this from being a free
        collectible" pattern _foot_clearance_reward() uses, see its own
        bug-fix note). Caller gates this by forward_progress, same as
        every other positive term here that's otherwise satisfiable by
        wiggling in place without genuinely walking (trot_symmetry_
        reward, tip_reward, feet_air_time_reward) -- a rapidly
        oscillating calf collects this reward regardless of whether the
        robot goes anywhere, so ungated it would be exactly the kind of
        "free reward, no forward progress required" exploit this
        project has repeatedly had to close elsewhere.

        CAPPED at CALF_SWING_REWARD_CAP (2026-08-05, see its own
        comment) -- unbounded, this rewarded a continuously-accelerating,
        never-reversing calf rotation MORE than a genuine bounded, cyclic
        swing, which is backwards: real reciprocating motion doesn't need
        or benefit from ever-growing velocity, so capping it costs a real
        gait nothing while closing the runaway-rotation exploit."""
        contacted = self._foot_contact_per_leg()
        swinging = [not c for c in contacted]
        if not any(swinging):
            return 0.0
        calf_qvel = self.data.qvel[self.motor_dof_adr[self.calf_idx]]
        total = sum(calf_qvel[i] ** 2 for i in range(4) if swinging[i])
        return min(total / sum(swinging), CALF_SWING_REWARD_CAP)

    def _foot_horizontal_speed_sq(self, leg_idx):
        """Squared horizontal (world x/y) speed of a leg's foot site right
        now, via MuJoCo's site-Jacobian velocity (mj_objectVelocity, world
        frame) -- used by _foot_slip_penalty() to tell a genuinely planted
        foot (near-zero) from one sliding/dragging while nominally in
        contact. Sites have no qvel of their own; mj_objectVelocity
        computes it correctly through the whole kinematic chain up to
        that site, unlike finite-differencing site_xpos across steps."""
        site_id = self.foot_site_ids[leg_idx]
        vel = np.zeros(6)  # [angular(3), linear(3)]
        mujoco.mj_objectVelocity(self.model, self.data, mujoco.mjtObj.mjOBJ_SITE, site_id, vel, 0)
        return float(np.dot(vel[3:5], vel[3:5]))

    def _foot_slip_penalty(self):
        """Penalizes a foot's horizontal velocity WHILE IN CONTACT with
        the ground -- i.e. sliding/dragging rather than gripping and
        holding. Adapted from a labmate's Go2/Genesis walk implementation
        (friend_code/go2_env_walk.py's _reward_foot_slip), ported to this
        project's MuJoCo site-velocity API and single-env structure.

        Complements _foot_clearance_reward(), which only judges SWING
        legs -- this judges STANCE legs instead. Before this term,
        nothing distinguished a foot that plants and holds from one that
        stays in ground contact but slides along the floor for the whole
        stance phase, which reads as "dragging" even though
        _foot_placement_terms() sees it as correct tip contact the whole
        time (2026-07-29, user: "the robot is dragging its feet on the
        ground, we do not want that").

        Returns <=0 (already negative -- weight with a POSITIVE
        coefficient, same convention as height_reward/drift_penalty)."""
        contacted = self._foot_contact_per_leg()
        total = 0.0
        for i in range(len(self.foot_site_ids)):
            if contacted[i]:
                total += self._foot_horizontal_speed_sq(i)
        return -total

    def _touchdown_velocity_penalty(self):
        """Penalizes a foot's vertical (world z) speed at the exact
        moment of landing (contact resuming after a nonzero air time) --
        a hard, uncushioned plant vs. a soft, controlled one. Real
        quadrupeds actively manage the knee right before touchdown to
        absorb impact; nothing in this reward previously distinguished
        that from a stiff, hard landing.

        Added 2026-07-30 after the user observed real but consistently
        SMALLER calf/knee articulation than the thighs on a walking
        policy (PPO_30000000_walk_policy_v4: verified directly, raw calf
        hinge range 35-63deg vs thigh range 55-74deg per leg -- the knee
        WAS bending, just less than the hip). No existing term
        differentiates WHICH joint produces a foot's motion, only the
        outcome (elevation, slip) -- so nothing was pushing toward the
        specific stability-relevant role a real knee plays at touchdown
        specifically, as opposed to during swing (already covered by
        _foot_clearance_reward). This targets that gap directly rather
        than just rewarding more calf motion in the abstract, since a
        soft landing is the part of real knee usage most directly tied
        to walking stability.

        MUST be called BEFORE _feet_air_time_reward() within the same
        tick -- both detect "landing" the same way (self._feet_air_time
        > 0 AND now in contact), but _feet_air_time_reward() resets that
        state to 0 as part of computing its own reward; calling this
        method afterward would see every leg as "not landing" and never
        fire. Uses the same post-mj_step timing as
        _foot_slip_penalty()/_foot_clearance_reward() -- doesn't isolate
        the exact pre-impact velocity (some absorption may already be
        reflected in this tick's own contact resolution), but the
        residual reported velocity still scales with impact severity,
        consistent with how every other contact-based term here works.

        Returns <=0 (already negative -- weight with a POSITIVE
        coefficient, same convention as foot_slip_penalty).

        CALIBRATION NOTE: verified firing correctly on
        PPO_30000000_walk_policy_v4 by observing the real production
        call path (monkey-patched, NOT a standalone re-invocation --
        calling this or _feet_air_time_reward() a second time after
        env.step() already ran the real _compute_reward_walk() internally
        just re-reads already-landing-consumed state and looks like it
        never fires, a test-methodology trap hit and corrected while
        adding this). Fires on ~3% of ticks (a landing event, not a
        continuous condition like foot_slip_penalty), raw magnitude
        ~-0.08 when firing -- weight needs to be much larger than a
        per-tick term's to have a comparable AVERAGE effect. Weighted
        5.0 (not 0.1) for that reason -- still a placeholder, not a
        formal sweep."""
        contacted = self._foot_contact_per_leg()
        total = 0.0
        for i in range(4):
            if contacted[i] and self._feet_air_time[i] > 0.0:
                site_id = self.foot_site_ids[i]
                vel = np.zeros(6)  # [angular(3), linear(3)]
                mujoco.mj_objectVelocity(self.model, self.data, mujoco.mjtObj.mjOBJ_SITE, site_id, vel, 0)
                total += vel[5] ** 2  # vertical (world z) linear speed squared
        return -total

    def _feet_air_time_reward(self):
        """Rewards a leg for swinging roughly FEET_AIR_TIME_TARGET_S
        before landing again -- a real step CADENCE, not just "was
        elevated at some point" (that's _foot_clearance_reward's job).
        Discourages both extremes: a leg that never truly lifts
        (shuffling/dragging, ~0 air time every landing) and a leg that
        stays airborne far longer than a normal swing (limping/dragging
        a stuck leg). Adapted from a labmate's Go2/Genesis walk
        implementation (friend_code/go2_env_walk.py's
        _reward_feet_air_time), ported to this project's per-step MuJoCo
        contact query, persistent per-leg timer (self._feet_air_time,
        seconds, reset in reset()), and single-env structure (no
        per-env command vector to gate on here, unlike the source --
        this project's walk task doesn't have a separate "standing
        still" command mode).

        Rewarded once per landing (the step contact resumes after a
        nonzero air time), scaled by how far that swing's duration was
        from the target -- positive if the swing ran long enough,
        negative if it was too short (foot barely left the ground).

        Also applies a GROWING per-tick penalty (see FEET_AIR_TIME_MAX_S)
        to a leg that's been airborne past that cap, EVERY tick it stays
        up -- not just at landing. Closes a real exploit found
        2026-07-29 (PPO_13000000_walk_policy_v3): a policy that lifts one
        leg and simply never re-plants it never triggers the landing-only
        check above at all, while scoring ~max on _foot_clearance_reward
        (which rewards elevation unconditionally, with no notion of how
        long the leg has been up) -- a strongly rewarding, exploitable
        local optimum with zero forward progress (leg airborne 98.7% of
        a 1000-step rollout, ~0.000m traveled). This term now costs that
        strategy real, growing reward regardless of whether the leg ever
        lands.

        MIRROR-IMAGE addition (2026-07-30, FEET_STANCE_TIME_MAX_S): the
        same growing per-tick penalty applied to a leg that's been
        PLANTED past that cap -- closes the symmetric gap. User reported
        the back legs "have always been dragging" (confirmed on
        PPO_10000000_walk_policy_v7: back legs airborne only 0.7-2.5% of
        a full 10s episode vs front legs' ~44%, much smaller knee range
        of motion) -- nothing previously penalized a leg for simply never
        swinging; foot_clearance_reward only judges swing legs,
        foot_slip_penalty only judges stance-phase SLIDING (a rigid,
        motionless planted leg costs nothing there), and the ABOVE
        air-time cap only catches legs stuck in the air, not stuck on
        the ground."""
        contacted = self._foot_contact_per_leg()
        dt = self.model.opt.timestep
        reward = 0.0
        for i in range(4):
            if contacted[i]:
                if self._feet_air_time[i] > 0.0:
                    reward += self._feet_air_time[i] - FEET_AIR_TIME_TARGET_S
                self._feet_air_time[i] = 0.0
                self._feet_stance_time[i] += dt
                if self._feet_stance_time[i] > FEET_STANCE_TIME_MAX_S:
                    reward -= (self._feet_stance_time[i] - FEET_STANCE_TIME_MAX_S)
            else:
                self._feet_air_time[i] += dt
                self._feet_stance_time[i] = 0.0
                if self._feet_air_time[i] > FEET_AIR_TIME_MAX_S:
                    reward -= (self._feet_air_time[i] - FEET_AIR_TIME_MAX_S)
        return reward

    def _foot_contact_state_per_leg(self):
        """['air'|'tip'|'nontip'] x4, in (leg_a, leg_b, leg_c, leg_d)
        order -- the single source of truth for per-leg ground contact,
        used by _foot_tip_contact_count()/_foot_contact_per_leg() below
        as well as diagnostics. Checks BOTH calf_geom_ids (knee->foot
        capsule -- 'tip' within FOOT_CONTACT_RADIUS_M of the true foot
        site, 'nontip' otherwise i.e. knee/shin dragging) AND
        thigh_geom_ids.

        THIGH contact (added 2026-08-03) always maps to 'nontip'
        unconditionally, no distance check -- a thigh can never BE the
        foot tip, so there's nothing to measure against. Added after a
        real, confirmed case (PPO_5000000_walk_policy_home_v18, a user-
        supplied qpos snapshot) where leg_a's thigh had a genuine MuJoCo
        contact with the floor (dist=-0.00374, not a rendering artifact)
        at the same instant its calf happened to ALSO register a clean
        tip contact -- the old calf-only version of this function
        classified that leg as 'tip' outright, completely blind to the
        thigh touching down, so nothing (non_tip_penalty,
        NONTIP_TERMINATION) ever saw it. Thigh contact is given
        PRIORITY over a same-step calf classification for that same leg
        (see the `continue` below) precisely to fix that exact case: a
        clean foot-tip plant does not excuse a simultaneously-grounded
        thigh.

        If a leg somehow registers more than one calf contact this step,
        the last one found wins (rare, only matters for the tip/nontip
        distinction, not whether contact happened at all)."""
        state = ['air'] * len(self.calf_geom_ids)
        for i in range(self.data.ncon):
            c = self.data.contact[i]
            for near, far in ((c.geom1, c.geom2), (c.geom2, c.geom1)):
                if near != self.floor_geom_id:
                    continue
                if far in self.thigh_geom_ids:
                    state[self.thigh_geom_ids.index(far)] = 'nontip'
                elif far in self.calf_geom_ids:
                    leg_idx = self.calf_geom_ids.index(far)
                    if state[leg_idx] == 'nontip':
                        continue  # thigh already flagged this leg -- don't let a
                                  # same-step calf-tip contact downgrade it back
                    foot_pos = self.data.site_xpos[self.foot_site_ids[leg_idx]]
                    is_tip = np.linalg.norm(np.array(c.pos) - foot_pos) < FOOT_CONTACT_RADIUS_M
                    state[leg_idx] = 'tip' if is_tip else 'nontip'
        return state

    def _foot_tip_contact_count(self):
        """(num_tip, num_non_tip): aggregate counts derived from
        _foot_contact_state_per_leg() (the single source of truth for
        per-leg contact classification, including thigh contact -- see
        that method's docstring)."""
        state = self._foot_contact_state_per_leg()
        return state.count('tip'), state.count('nontip')

    def _foot_placement_terms(self):
        """(tip_reward, non_tip_penalty) shared by both tasks: tip_reward
        in [0, 1] is the fraction of the 4 feet grounded at the actual
        foot tip; non_tip_penalty is <=0, scaled by how many contacts are
        happening away from the tip instead (knee/shin dragging -- e.g.
        a trained walk policy observed doing exactly this)."""
        num_tip, num_non_tip = self._foot_tip_contact_count()
        return num_tip / 4.0, -1.0 * num_non_tip

    def _is_fallen(self):
        if self._torso_height() < FALL_HEIGHT_M:
            return True
        max_tilt = WALK_MAX_TILT_RAD if self.task == 'walk' else MAX_TILT_RAD
        if self._torso_up_z() < np.cos(max_tilt):
            return True
        return False

    def _update_nontip_contact_time(self):
        """Advances self._non_tip_contact_time per leg -- MUST be called
        once per step, after mj_step (so contact state reflects the step
        just taken). Grows while a leg stays in CONTINUOUS non-tip
        contact, resets to 0 the instant that leg is either airborne or
        back on the true tip -- a single-step recovery is enough to clear
        it, only a sustained bad landing accumulates. See
        NONTIP_TERMINATION_S's comment for why this is soft
        (duration-based) rather than firing on the first bad touch."""
        state = self._foot_contact_state_per_leg()
        dt = self.model.opt.timestep
        for i in range(4):
            if state[i] == 'nontip':
                self._non_tip_contact_time[i] += dt
            else:
                self._non_tip_contact_time[i] = 0.0

    def _update_airborne_time(self):
        """Advances self._airborne_time per leg -- MUST be called once
        per step, after mj_step. Grows while a leg stays in CONTINUOUS
        full airborne (no contact at all -- tip, knee, or thigh), resets
        to 0 the instant that leg touches down again. Same soft
        (duration-based) reasoning as _update_nontip_contact_time() --
        see STAND_AIRBORNE_TERMINATION_S's comment."""
        contacted = self._foot_contact_per_leg()
        dt = self.model.opt.timestep
        for i in range(4):
            if not contacted[i]:
                self._airborne_time[i] += dt
            else:
                self._airborne_time[i] = 0.0

    def _update_leg_phase_time(self):
        """Advances self._leg_phase_time per leg -- seconds since that
        leg's contact state (grounded vs swinging, from
        _foot_contact_per_leg()) last changed, either direction. Resets
        to 0 the tick a leg's phase flips, otherwise accumulates. MUST be
        called once per step, after mj_step and BEFORE _compute_reward()
        (unlike _update_nontip_contact_time(), which is only consumed by
        the post-reward termination check) -- _trot_symmetry_reward()
        reads this value and needs it current for the tick just taken.

        Added 2026-08-05 after measuring walk_position_scratch_v1/
        walk_position_imitation_v1 both converge to a "tumbling" local
        optimum: a single non-reciprocating thigh sweep (one diagonal
        pair lifts once and never plants again) scored a sustained
        PERFECT trot_symmetry_reward for 100+ ticks, because that reward
        was purely instantaneous -- it checked which 4 legs were up/down
        THIS tick, never whether the pattern had ever alternated. This
        timer is what lets _trot_symmetry_reward() tell "genuinely
        trotting" apart from "one leg has been stuck mid-swing for over
        a second."""
        contacted = np.array(self._foot_contact_per_leg())
        dt = self.model.opt.timestep
        changed = contacted != self._prev_leg_contact
        self._leg_phase_time[changed] = 0.0
        self._leg_phase_time[~changed] += dt
        self._prev_leg_contact = contacted

    def _update_high_pitch_time(self):
        """Advances self._high_pitch_time -- seconds torso pitch
        magnitude has stayed CONTINUOUSLY above
        PITCH_TERMINATION_THRESHOLD_RAD, resetting to 0 the instant it
        dips back below (same reset-on-recovery pattern as
        _update_nontip_contact_time()/_update_leg_phase_time()). MUST be
        called once per step, after mj_step -- see
        _pitch_diverging_too_long()."""
        dt = self.model.opt.timestep
        if abs(self._torso_pitch_rad()) > PITCH_TERMINATION_THRESHOLD_RAD:
            self._high_pitch_time += dt
        else:
            self._high_pitch_time = 0.0

    def _leg_stuck_too_long(self):
        """WALK only: True if any leg has held the SAME contact phase
        (grounded or swinging, self._leg_phase_time) for longer than
        LEG_PHASE_TERMINATION_S -- see that constant's comment. Reuses
        the exact state _trot_symmetry_reward()'s MAX_LEG_PHASE_S gate
        already tracks; this just also ends the episode instead of only
        scoring it worse, once a leg's clearly not participating in a
        real gait."""
        if self.task != 'walk':
            return False
        return bool(np.any(self._leg_phase_time > LEG_PHASE_TERMINATION_S))

    def _pitch_diverging_too_long(self):
        """WALK only: True if torso pitch has stayed above
        PITCH_TERMINATION_THRESHOLD_RAD continuously for longer than
        PITCH_TERMINATION_DURATION_S -- see that constant's comment. A
        much more sensitive, earlier-triggering signal than
        _is_fallen()'s ~20deg WALK_MAX_TILT_RAD threshold, specifically
        for a torso that's leaning and NOT recovering."""
        if self.task != 'walk':
            return False
        return self._high_pitch_time > PITCH_TERMINATION_DURATION_S

    def _no_forward_progress(self):
        """WALK only: True if, past an initial NO_PROGRESS_GRACE_S grace
        period, this episode still hasn't moved NO_PROGRESS_MIN_
        DISTANCE_M net forward (world +y, same axis forward_velocity_
        reward uses) from self._episode_start_y -- see that constant's
        comment. A general backstop for "nothing productive is
        happening," distinct from the two failure-mode-specific checks
        above."""
        if self.task != 'walk':
            return False
        elapsed_s = self._step_count * self.model.opt.timestep
        if elapsed_s < NO_PROGRESS_GRACE_S:
            return False
        forward_displacement = self.data.xpos[self.torso_body_id][1] - self._episode_start_y
        return forward_displacement < NO_PROGRESS_MIN_DISTANCE_M

    def _knee_walking_too_long(self):
        """True if any leg has been in continuous non-tip (knee/thigh/shin)
        contact for longer than NONTIP_TERMINATION_S. BOTH tasks
        (2026-08-04 -- originally WALK only; STAND's grounded_reward
        already SCORES true tip contact via height_progress-gated
        grounded_reward, but had no analogous "give up and end the
        episode" termination until the user asked for one, matching
        WALK's existing mechanism). No-ops entirely (always False) if
        NONTIP_TERMINATION_ENABLED is off."""
        if not NONTIP_TERMINATION_ENABLED:
            return False
        return bool(np.any(self._non_tip_contact_time > NONTIP_TERMINATION_S))

    def _not_all_feet_grounded(self):
        """STAND only: True if any leg has been fully airborne (no floor
        contact at all -- tip, knee, or thigh) for longer than
        STAND_AIRBORNE_TERMINATION_S continuously, i.e. the robot has
        genuinely stopped resting on all 4 legs, not just a momentary
        noise-driven twitch. Added 2026-08-07 (user request:
        PPO_1000000_stand_position_obshistory_v1 was observed learning
        to balance on 3 legs instead of genuinely standing on all 4).

        SOFTENED to a duration threshold same day, same user's own
        request, after measuring the original instant/zero-grace version
        directly: under PPO's normal STOCHASTIC exploration noise (what
        training actually rolls out, not the deterministic eval policy),
        it terminated ~20 ticks in on average, EVERY episode (20/20
        tested) -- even though the SAME checkpoint's deterministic
        policy never triggered it at all across a full 1000-tick
        episode. The instant version was catching ordinary exploration
        jitter, not genuine bad standing, and was starving training of
        real experience. See STAND_AIRBORNE_TERMINATION_S's comment."""
        if self.task != 'stand':
            return False
        return bool(np.any(self._airborne_time > STAND_AIRBORNE_TERMINATION_S))

    def _common_penalties(self, action):
        """Terms both tasks share: IMU-based shock penalty + effort + a
        per-step survival bonus. action_rate_penalty and
        angular_vel_penalty are NOT here -- see _action_rate_penalty()/
        _angular_vel_penalty() below, both computed separately per task
        since stand and walk need genuinely different weighting for each
        (walk needs continuous leg motion forever, so action_rate can't
        be gated toward "should be still" the way stand's climb-then-hold
        structure can; walk's own forward-speed incentive can also make
        a shared angular-velocity weight get run over -- see
        _angular_vel_penalty()'s comment)."""
        # sensordata layout matches the <sensor> block in dog.mjcf.xml:
        # [0:3] accelerometer, [3:6] gyro.
        linear_accel = self.data.sensordata[0:3]
        gravity_m_s2 = 9.81
        accel_shock_penalty = -0.01 * (np.linalg.norm(linear_accel) - gravity_m_s2) ** 2

        # SCALE BUG FIXED 2026-08-04: this -0.001 weight was calibrated
        # against position mode's action (radians, ~4-8 rad span per
        # motor). control_mode='torque' actions are in N*m (+-20 span,
        # see WALK/STAND_ACTION_RESIDUAL... no -- see control_mode's
        # comment in __init__) -- unnormalized, max-torque-on-every-motor
        # costs -3.2 here, dwarfing height_reward's entire ~0.5 ceiling
        # even before counting _action_rate_penalty's much larger version
        # of the same bug (see that method). Found diagnosing
        # stand_policy_torque_v2: mean |action| was 0.1-1.2 out of a +-20
        # range at 1M steps -- the policy had learned to barely apply any
        # torque at all, because doing so was reward-negative regardless
        # of whether it helped stand up. Normalizing by the actuator's
        # own range (symmetric for <motor>, so dividing by .high alone is
        # valid) makes this weight mean the same thing regardless of
        # control_mode's physical units -- NOT applied to position mode,
        # whose calibration (and every existing trained checkpoint) this
        # must not disturb.
        if self.control_mode in ('torque', 'torque_belt'):
            normalized_action = action / self.action_space.high
            effort_penalty = -0.001 * float(np.dot(normalized_action, normalized_action))
        else:
            effort_penalty = -0.001 * float(np.dot(action, action))

        survival_bonus = 0.05

        return accel_shock_penalty + effort_penalty + survival_bonus

    def _angular_vel_penalty(self, weight):
        """weight * dot(angular_vel, angular_vel) -- caller supplies the
        weight, same pattern as _action_rate_penalty() below.

        History: -0.02 was the ORIGINAL, shared value (both tasks, via
        _common_penalties). Split out and given a walk-specific,
        stronger weight 2026-07-30 after the user observed a walk policy
        (PPO_18000000_walk_policy_v5) still wobbling a lot despite
        forward tilt and upright score both clearly converging with more
        training (15.1->10.1->5.8deg mean pitch, 0.962->0.976->0.980
        upright across 6M/12M/18M) -- torso angular velocity (the direct
        wobble measure) was doing the OPPOSITE, getting WORSE with more
        training (mean 0.35->0.74->0.84 rad/s, peak 0.99->1.67->2.25
        rad/s). Measured directly: at the shared -0.02 weight, this
        term's weighted contribution (-0.0148/step) was 66x SMALLER than
        forward_velocity_reward's (+0.9801/step, itself raised 2.0->5.0
        on 2026-07-29 to fix a different exploit) -- the policy has
        essentially free rein to trade stability for speed, since
        wobbling costs almost nothing relative to what it gains by going
        faster. Stand keeps the original -0.02 (unaffected, standing
        still has no comparable "worth it for speed" incentive pulling
        against this term). Walk gets -0.2 (10x), calibrated to give a
        real, competitive cost (~-0.15/step at the measured wobble level,
        roughly 15% of forward_velocity_reward's magnitude -- enough to
        matter without eliminating forward motion outright). Still a
        placeholder, not a formal sweep."""
        angular_vel = self.data.sensordata[3:6]
        return weight * float(np.dot(angular_vel, angular_vel))

    def _action_rate_penalty(self, action, weight):
        """weight * sum((action - prev_action)**2) -- caller supplies the
        weight so stand (gated by height_progress, see
        ACTION_RATE_PENALTY_WEIGHT_RISING/STANDING) and walk (flat) can
        each use their own logic. History: raised 10x (-0.01 -> -0.1,
        2026-07-27) after real-hardware deployment of a "converged"-
        looking stand policy (calfFix_stand_policy_v5, 3-6M timesteps)
        showed persistent tick-to-tick chatter even at a fully settled
        stand pose -- traced to the RAW POLICY ACTION itself (not
        firmware, not real sensor noise, not the deploy clamp -- confirmed
        directly in clean sim with zero real-hardware noise involved):
        consecutive deterministic actions at a genuinely settled state
        swung by 10-30deg step-to-step. DogEnv.step()'s own slew clamp
        (MAX_SLEW_DEG_PER_S) rate-limits the PHYSICAL consequence during
        training, same as dog_deploy/policy_node.py's clamp does at
        deploy time -- but neither clamp can fix an underlying signal
        that keeps reversing direction; they only rate-limit how fast it
        chases itself back and forth forever. At the OLD flat weight
        (-0.01), a representative multi-motor jitter contributed roughly
        -0.01 to total reward per step -- negligible next to
        height_reward (weight 3.0) or upright_reward (weight 2.0).
        FURTHER FINDING (2026-07-29): a UNIFORM weight (even at -0.1)
        still wasn't enough for the stand task specifically -- had to be
        small enough to not fight the genuinely large, necessary
        corrective actions during the RISE, which caps how hard it can
        push once already standing. See ACTION_RATE_PENALTY_WEIGHT_
        RISING/STANDING and _compute_reward_stand()'s height_progress
        gating below -- same "gate by climb progress" pattern
        upright_reward/grounded_reward already use, applied here for
        the first time (TODO 16 in daniel_cl_context.md).

        SCALE BUG FIXED 2026-08-04 (same root cause as effort_penalty's
        matching fix in _common_penalties(), much bigger impact here):
        unnormalized, a full torque-mode swing (delta up to 40 per motor,
        N*m units) costs up to -1280 to -5120 depending on which weight
        is active -- thousands of times larger than height_reward's
        entire ~0.5 ceiling. This was the DOMINANT cause of
        stand_policy_torque_v2 barely applying any torque at all (mean
        |action| 0.1-1.2 out of +-20 at 1M steps): any real torque
        commitment was reward-catastrophic regardless of whether it
        helped stand up, so near-zero action was the only locally safe
        policy. Normalized the same way as effort_penalty -- NOT applied
        to position mode, whose calibration (and every existing trained
        checkpoint) this must not disturb."""
        delta = action - self.prev_action
        if self.control_mode in ('torque', 'torque_belt'):
            delta = delta / self.action_space.high
        return weight * float(np.sum(delta ** 2))

    def _compute_reward(self, action):
        if self.task == 'stand':
            return self._compute_reward_stand(action)
        return self._compute_reward_walk(action)

    def _compute_reward_stand(self, action):
        # UNCAPPED height reward (2026-08-04, user request: "make the
        # robot stand to its maximum height") -- was -abs(height -
        # STAND_HEIGHT_M), which penalized exceeding STAND_HEIGHT_M
        # exactly as much as falling short of it. STAND_HEIGHT_M is only
        # ever a hand-posed APPROXIMATION of "near max" (see its own
        # comment), not a verified true maximum, so treating it as a
        # target to match rather than a floor to clear was actively
        # capping the policy below whatever the real achievable max is.
        # Relative to SIT_HEIGHT_M (not raw torso_height) so the scale/
        # slope stays comparable to the old term (same ~0 at sitting,
        # growing with height) -- just uncapped above STAND_HEIGHT_M
        # instead of penalized there.
        height_reward = self._torso_height() - SIT_HEIGHT_M
        height_error = abs(self._torso_height() - STAND_HEIGHT_M)
        # Bonus on top of the continuous shaping term once within
        # tolerance -- gives "close enough" a distinctly better return
        # than "still closing in", per the requested error tolerance.
        # Still anchored on STAND_HEIGHT_M as a known-reachable
        # checkpoint bonus, layered under the uncapped term above (which
        # keeps pushing higher if more height is actually achievable).
        height_bonus = 0.2 if height_error < STAND_HEIGHT_TOLERANCE_M else 0.0

        # Gate uprightness by standing progress (0 at sitting height, 1 at
        # the target) instead of paying it out unconditionally -- an
        # unconditional +upright term made "sit still and level" collect
        # most of the achievable reward on its own (observed: trained
        # policy barely moved 2 of 8 motors, ep_rew_mean matched the
        # sit-still-forever estimate almost exactly), removing any real
        # pressure to actually climb to standing height. Now sitting
        # level scores near zero on this term instead of the max.
        height_progress = np.clip(
            (self._torso_height() - SIT_HEIGHT_M) / (STAND_HEIGHT_M - SIT_HEIGHT_M), 0.0, 1.0)
        upright_reward = self._torso_up_z() * height_progress  # 1.0 = perfectly level AND at height

        motor_qpos = self.data.qpos[self.motor_qpos_adr]
        # THIGH_SYMMETRY_SIGN/CALF_SYMMETRY_SIGN correct for the left/right
        # (thigh) and front/back (calf) mirrored joint axes before
        # comparing -- see STANDING_QPOS_DEG's comment.
        thigh_spread = np.var(motor_qpos[SYMMETRIC_THIGH_IDX] * THIGH_SYMMETRY_SIGN)
        calf_spread = np.var(motor_qpos[SYMMETRIC_CALF_IDX] * CALF_SYMMETRY_SIGN)
        symmetry_penalty = -1.0 * (thigh_spread + calf_spread)

        # Standing still means staying in place, not just staying up --
        # qvel[0:2] is the free joint's world-frame x/y linear velocity.
        drift_penalty = -0.1 * float(np.dot(self.data.qvel[0:2], self.data.qvel[0:2]))

        # All 4 feet should be on the ground AT THE FOOT TIP once actually
        # standing (user observed a trained policy reaching the target
        # height on only 3 legs, and separately a walk policy standing on
        # its knees instead of its feet -- _foot_placement_terms()
        # distinguishes tip contact from knee/shin contact, unlike a raw
        # calf-capsule contact check). Gated by height_progress the same
        # way upright_reward is, since feet legitimately leave the ground
        # (and can brush the knee/shin) while still climbing from the
        # sitting pose -- only penalize/reward this once close to standing.
        tip_reward, non_tip_penalty = self._foot_placement_terms()
        # AIRBORNE PENALTY ADDED 2026-08-07 (multi-agent review w/
        # Antigravity, chatbot.md "3-legged standing came back" -- user
        # request "add termination for not on all 4 legs" led to adding
        # STAND_AIRBORNE_TERMINATION_S's grace period first, but that
        # alone only controls WHEN the episode ends, not whether standing
        # on 3 legs costs anything in the meantime. Measured directly on
        # PPO_1000000_stand_position_obshistory_v7: a leg lifted once at
        # step ~15 and simply stayed up for the entire 3s grace window,
        # since a fully airborne leg previously counted as neither 'tip'
        # nor 'non_tip' in _foot_placement_terms() -- tip_reward only
        # dropped 1.0->0.75, a max ~0.375 per-tick cost at this term's
        # 1.5 weight, dwarfed by upright_reward's ~2.0/tick (which
        # doesn't care how many feet are grounded at all). Subtracting
        # num_airborne_legs directly in this term's own formula flips a
        # single airborne leg from a NET GAIN (+1.5) to a NET LOSS
        # (-0.375) at this weight -- a ~1.9 swing, now comparable to
        # upright_reward's own weight instead of a token dilution.
        num_airborne_legs = 4 - sum(self._foot_contact_per_leg())
        grounded_reward = (tip_reward + non_tip_penalty - num_airborne_legs) * height_progress

        # Gated by height_progress, same pattern as upright_reward/
        # grounded_reward above -- see ACTION_RATE_PENALTY_WEIGHT_RISING/
        # STANDING's comment and TODO 16 in daniel_cl_context.md. Weak
        # during the climb (doesn't fight genuinely-needed large
        # corrective actions), much stronger once actually standing
        # (nothing legitimately needs a large action anymore then).
        action_rate_weight = (
            ACTION_RATE_PENALTY_WEIGHT_RISING
            + (ACTION_RATE_PENALTY_WEIGHT_STANDING - ACTION_RATE_PENALTY_WEIGHT_RISING) * height_progress
        )
        action_rate_penalty = self._action_rate_penalty(action, action_rate_weight)
        angular_vel_penalty = self._angular_vel_penalty(STAND_ANGULAR_VEL_PENALTY_WEIGHT)

        # NEW 2026-08-04 (user request, real-hardware motivated): direct
        # penalty on JOINT velocity (qvel), distinct from angular_vel_
        # penalty above (that's the TORSO's angular velocity from the
        # IMU/gyro, torso wobble -- this is the 8 motors' own velocity).
        # Nothing previously penalized this at all -- the observation
        # already includes motor_qvel every tick, so the policy has
        # always had the information needed to notice "I'm spinning fast
        # right now" and react, it just had no reason to. Motivated by a
        # real breakaway event (see TORQUE_KD_GAIN's comment): static
        # friction held a thigh motionless under climbing commanded
        # torque, then it broke free and ran away to 1682 deg/s with
        # nothing (reward-wise) telling the policy that was bad.
        # Quadratic, so ordinary controlled motion (~20deg/s = ~0.35rad/s
        # per motor) costs very little (~0.01 weighted) while a runaway
        # spike (~1000+deg/s = ~17.5rad/s) costs enormously (~24+
        # weighted) -- deliberately asymmetric, doesn't fight normal
        # movement but dominates everything else the instant velocity
        # spikes. Applies regardless of control_mode (fast real joint
        # motion is a hazard either way) -- weight 0.01 is an untuned
        # placeholder, calibrated only by this back-of-envelope scaling,
        # not a formal sweep.
        motor_qvel = self.data.qvel[self.motor_dof_adr]
        joint_velocity_penalty = -float(np.dot(motor_qvel, motor_qvel))

        # action_rate_penalty/common_penalties ZEROED (2026-08-04, user
        # request, matching _compute_reward_walk()'s simple_rewards
        # treatment) -- NOT deleted, same convention as that branch (flip
        # the coefficient back to 1.0 to restore). This return was never
        # touched by the original simple_rewards experiment (that only
        # zeroed WALK's terms), which turned out to matter for
        # control_mode='torque': measured directly on stand_policy_torque_v4
        # (2M steps) that STAND, still carrying these two terms at real
        # weight, had settled into a static, WRONG-SIGNED, low-magnitude
        # action (mean |action| 2-3 out of +-20) while WALK (already
        # zeroed) was freely exploring toward a real, correctly-signed
        # push -- action_rate_penalty rewards keeping the action similar
        # step-to-step, which gave STAND no pressure to escape an early,
        # accidentally-wrong-signed local optimum once it settled there.
        # ruled out accel_shock_penalty as an alternative explanation
        # first (measured: a genuine stand-up attempt has a SMALLER
        # shock penalty than doing nothing, -0.73 vs -1.73 over 3s) --
        # this asymmetry was the real, confirmed cause.
        return (
            3.0 * height_reward
            + height_bonus
            + 2.0 * upright_reward
            + 1.5 * grounded_reward
            + symmetry_penalty
            + drift_penalty
            + 0.0 * action_rate_penalty
            + angular_vel_penalty
            + 0.01 * joint_velocity_penalty
            + 0.0 * self._common_penalties(action)
        )

    def _compute_reward_walk(self, action):
        # dog.mjcf.xml is still in the CAD's own native frame (+y=front,
        # +x=right -- see the model's own header comment), NOT yet
        # remapped to ROS REP-103 (+x=forward). qvel[1] is therefore the
        # real forward velocity here, not qvel[0] (an earlier version of
        # this line used qvel[0] under the wrong assumption that +x was
        # already forward -- confirmed as the cause of a policy that
        # leaned/drifted rightward instead of walking forward after a
        # full 22M-timestep training run, since qvel[0] literally rewards
        # rightward motion in this frame). Revisit this line together with
        # the frame remap if that ever gets applied.
        forward_velocity_reward = self.data.qvel[1]
        # Gated by forward progress (0 at zero/negative velocity, 1 at
        # WALK_FORWARD_PROGRESS_TARGET_M_S+) -- mirrors the stand task's
        # own height_progress gate on its upright_reward, same underlying
        # reason: an UNCONDITIONAL upright_reward was collectible almost
        # in full just by standing mostly still and level, with no
        # requirement to actually walk. Measured directly on
        # PPO_21000000_walk_policy_v9 (2026-07-30): a near-stationary,
        # drifting-backward policy scored upright_reward=+0.4965/step
        # (near its 0.5 max) while forward_velocity_reward was only
        # -0.0896/step and the movement-triggered penalties (wobble,
        # pitch) stayed small precisely BECAUSE the robot wasn't moving
        # -- "stay safe and still" was a more reliable reward-collection
        # strategy than attempting real dynamic walking, which risks
        # several other movement-triggered penalties at once. This
        # closes that specific escape hatch directly.
        forward_progress = np.clip(forward_velocity_reward / WALK_FORWARD_PROGRESS_TARGET_M_S, 0.0, 1.0)
        # CAPPED 2026-08-04 (user: "I want the robot to move slowly...
        # the robot is not moving smoothly") -- was uncapped raw qvel[1],
        # the ONLY term in this whole function with no ceiling at
        # WALK_FORWARD_PROGRESS_TARGET_M_S: every other term that
        # references that target (upright_reward above, trot_symmetry_
        # reward, feet_air_time_reward) maxes out there and stops giving
        # more credit, but forward_velocity_reward kept rewarding MORE
        # speed unboundedly. Measured directly on walk_policy_torque_v7
        # @9M: mean forward velocity 0.65 m/s -- over 4x the 0.15 m/s
        # every other term already treated as "done" -- with 2+ legs
        # airborne simultaneously 96.5% of the time.
        #
        # REFORMULATED 2026-08-06 (multi-agent review w/ Antigravity,
        # chatbot.md "v10 leans and tumbles, still gains reward"
        # investigation): the plain min()-cap above removed the "gallop
        # for more reward" incentive but only in one direction -- it
        # stopped giving MORE credit past target, it never made
        # overshoot actually cost anything. Measured directly on
        # PPO_1000000_walk_position_obshistory_v10: during a forward
        # dive, weighted reward stayed pinned at its 0.750 ceiling while
        # raw velocity climbed to 0.346 m/s (2.3x target) -- zero
        # downside for a lunge wildly exceeding the intended walking
        # pace. Below target, behavior is UNCHANGED (still the same
        # linear ramp 0->target, same incentive to accelerate up to a
        # real walking pace, still equal to min(raw, target) there).
        # Above target: one-sided Gaussian falloff from the peak value
        # (sigma = target itself, same convention as
        # _foot_clearance_reward()'s own Gaussian reformulation) --
        # overshoot now actively costs instead of being free.
        if forward_velocity_reward > WALK_FORWARD_PROGRESS_TARGET_M_S:
            overshoot = forward_velocity_reward - WALK_FORWARD_PROGRESS_TARGET_M_S
            sigma = WALK_FORWARD_PROGRESS_TARGET_M_S
            forward_velocity_reward = WALK_FORWARD_PROGRESS_TARGET_M_S * np.exp(
                -(overshoot ** 2) / (2 * sigma ** 2))

        # PITCH-GATED 2026-08-06 (same investigation as above): the
        # additive pitch_penalty further below was measured too weak to
        # counteract this term during an actual forward dive (only
        # -0.164 weighted at 13.4deg pitch vs +0.750 here, on the same
        # v10 checkpoint). Rather than leave it as a tug-of-war between
        # two additive terms of very different magnitude, gate the
        # reward itself by pitch so speed and tipping can't be traded
        # off -- moving fast while tipping over becomes structurally
        # incapable of scoring highly. sigma = PITCH_TERMINATION_
        # THRESHOLD_RAD (10deg): barely touches a normal walking gait's
        # small pitch oscillation (~5deg -> ~88% credit retained) but
        # sharply discounts a real dive (13.4deg -> ~41%, all the way to
        # ~14% at WALK_MAX_TILT_RAD's 20deg hard-fall boundary). Only
        # applied when forward_velocity_reward is positive -- this is
        # meant to stop REWARDING fast-while-tipping, not to shrink the
        # existing penalty for backward drift when pitch also happens to
        # be off (that's still fully penalized regardless of pitch).
        if forward_velocity_reward > 0:
            pitch_gate = np.exp(
                -(self._torso_pitch_rad() ** 2) / (2 * PITCH_TERMINATION_THRESHOLD_RAD ** 2))
            forward_velocity_reward = forward_velocity_reward * pitch_gate
        upright_reward = self._torso_up_z() * forward_progress
        # See _trot_symmetry_reward()'s docstring -- gated by the SAME
        # forward_progress as upright_reward, for the same reason (this
        # term is partially satisfiable by standing still, so it needs
        # the same "must actually be walking" gate).
        #
        # STUCK-PHASE BRANCH LEFT UNGATED (2026-08-07, multi-agent review
        # w/ Antigravity, chatbot.md "v11 does a split, stops walking
        # forward" investigation): _trot_symmetry_reward() already
        # returns a hard -1.0 the instant any leg holds its phase past
        # MAX_LEG_PHASE_S -- that part was firing correctly, but
        # multiplying it by forward_progress silently erased it exactly
        # when it mattered most, since a stuck leg naturally also drives
        # forward velocity (and therefore forward_progress) toward zero.
        # Measured directly on PPO_2000000_walk_position_obshistory_v11:
        # two legs stayed continuously planted for the ENTIRE 302-step
        # episode (leg_phase_time climbing unbroken from 0 straight to
        # the 3.0s LEG_PHASE_TERMINATION_S hard cutoff) while this -1.0
        # penalty sat multiplied down to ~0 the whole time -- the only
        # thing left punishing the freeze was the lump-sum termination
        # 3 full seconds later. The normal instantaneous-pattern branch
        # below is still gated exactly as before (a perfectly-timed trot
        # pattern while standing still still shouldn't score high) --
        # only the stuck-phase branch is now unconditional, since a
        # frozen leg is worse, not better-excused, when the robot has
        # also stopped moving.
        leg_stuck = bool(np.any(self._leg_phase_time > MAX_LEG_PHASE_S))
        trot_symmetry_reward = (
            self._trot_symmetry_reward() if leg_stuck
            else self._trot_symmetry_reward() * forward_progress)
        # Targets self._walk_target_height_m (walk_height_fraction * full
        # standing height, see __init__/WALK_HEIGHT_FRACTION's comment),
        # not the stand task's full STAND_HEIGHT_M: a crouched walking
        # height keeps the CoM lower and legs bent, discouraging both
        # crawling/belly-flopping AND an overextended, easy-to-topple
        # near-max-height stance. Weight raised 0.2 -> 0.6 alongside the
        # target change (still well below forward_velocity_reward's 2.0,
        # so it shapes rather than dominates, but a "loose regularizer"
        # weight wasn't enough to reliably hold this if the goal is a
        # real height-based stability guarantee -- reassess based on
        # the next walk training run's actual height-tracking behavior).
        height_reward = -abs(self._torso_height() - self._walk_target_height_m)

        # Walk on the feet, not the knees/shins -- this task previously had
        # NO foot-placement term at all, which is exactly why a trained
        # policy was observed walking on its knees: nothing in the reward
        # distinguished that from walking on its feet.
        tip_reward, non_tip_penalty = self._foot_placement_terms()
        # GATED by forward_progress (2026-08-03) -- same pattern/reason as
        # upright_reward and trot_symmetry_reward: measured directly on
        # walk_policy_home_v2 (1M steps, --walk-start-pose home) at
        # 1.10/step weighted (73% of its 1.5 ceiling) while
        # forward_velocity_reward was only 0.066/step -- a ~17x gap, with
        # forward distance ~0.013 m/s (essentially not moving). Ungated,
        # correct tip contact is fully collectible whether or not the body
        # ever translates -- ungating it was itself the earlier mistake
        # (comment used to say "not gated... walk task is always meant to
        # be standing/walking, never mid-climb", which stopped being true
        # once --walk-start-pose home was added: a home-start episode DOES
        # have a real climb phase, exactly where "reward feet contact
        # regardless of movement" is most exploitable). non_tip_penalty
        # left ungated -- currently zeroed anyway (see the return
        # statement), and it's a penalty (discourages knee-walking
        # unconditionally), not a positive term with a standing-still
        # escape hatch the way tip_reward has.
        tip_reward = tip_reward * forward_progress

        # This alone wasn't enough -- a later, much-longer-trained walk
        # policy (43M timesteps) converged back to knee-walking despite
        # the above, because tip_reward only judges WHERE contact happens
        # when it happens, not whether a leg ever lifts at all. A policy
        # that drags the true foot tip along the ground continuously,
        # never swinging, satisfies tip_reward perfectly while still never
        # producing a real gait. _foot_clearance_reward() closes that gap
        # by rewarding swinging (non-contacting) legs for actually being
        # elevated -- adapted from the standard feet_air_time/
        # foot_clearance pattern in quadruped locomotion RL (a labmate's
        # Go2/Genesis implementation, friend_code/go2_env_walk.py, uses
        # the same idea).
        # PARTIAL gate (2026-08-02): walk_policy_v14 measured this term at
        # 1.84/step weighted (near its ceiling) while forward_velocity_reward
        # was only 0.024/step weighted -- a ~75x gap, with legs a/d swinging
        # 76-85% of the episode for ~0.05m of actual forward travel over 10s.
        # Ungated, this is fully satisfiable by bobbing legs up and down in
        # place. A FULL gate (matching upright_reward/trot_symmetry_reward's
        # pattern) risks the same bootstrap problem flagged for those terms
        # (TODO in daniel_cl_context.md, v9 era): a robot that hasn't started
        # moving forward yet would then get zero credit for its very first
        # liftoffs, which is what needs encouraging in order to ever start
        # moving in the first place. Split the difference: never fully zero,
        # but scaled down to half strength until real forward progress exists.
        foot_clearance_reward = self._foot_clearance_reward() * (0.5 + 0.5 * forward_progress)

        # NEW 2026-08-04 (user request, see _calf_swing_motion_reward()'s
        # own docstring for the full "stiff-legged gait" diagnosis this
        # is meant to fix). FULLY gated by forward_progress (not the
        # partial foot_clearance_reward gate above) -- a rapidly
        # oscillating calf costs nothing to fake while standing still,
        # so this needs the same full gate as trot_symmetry_reward/
        # tip_reward/feet_air_time_reward, not clearance's softer
        # bootstrap-friendly treatment (this term isn't needed to
        # bootstrap the very first liftoff the way clearance is).
        calf_swing_motion_reward = self._calf_swing_motion_reward() * forward_progress

        # foot_clearance_reward only judges SWING legs (rewards them for
        # being elevated); nothing above judges STANCE legs, so a policy
        # could still satisfy every term while sliding a planted foot
        # along the ground the whole stance phase -- reads as dragging.
        # foot_slip_penalty closes that gap; feet_air_time_reward adds a
        # real swing-duration CADENCE on top of clearance's "was it off
        # the ground" check. Both new 2026-07-29 (user: "the robot is
        # dragging its feet on the ground... we want it to lift its feet
        # when moving forward") -- see each method's own docstring for
        # the friend_code/go2_env_walk.py source and adaptation notes.
        #
        # WEIGHTS RAISED same day, checked against real measured behavior
        # of PPO_16000000_walk_policy_v2 (not a blind guess): that
        # checkpoint's legs were airborne 0.0-0.3% of a 1000-step
        # rollout (essentially always dragging), zero landing events, yet
        # scored foot_clearance_reward=0.9957 mean (see that method's bug
        # fix note -- the "no leg swinging" fallback used to secretly
        # return the MAXIMUM score) while foot_slip_penalty's weighted
        # contribution (-0.019/step at the old 0.1 weight) was ~14x
        # smaller than forward_velocity_reward's (+0.262/step) -- dragging
        # was essentially free. foot_slip_penalty: 0.1 -> 1.0 (10x, makes
        # it a real, competitive cost against forward progress).
        # foot_clearance_reward: 0.75 -> 1.0 (now that the fallback bug is
        # fixed, this term will finally respond to real exploration --
        # strengthened since it's the direct per-tick lift-height signal,
        # denser than feet_air_time_reward's landing-only payout).
        # feet_air_time_reward's weight left unchanged: it literally
        # cannot contribute anything until legs start swinging at all
        # (zero landing events -> zero gradient regardless of weight) --
        # its job is refining swing DURATION once lifting already exists,
        # not bootstrapping the initial exploration; the two changes
        # above are what's meant to unstick that. Still placeholders, not
        # a formal sweep -- re-check with the same measurement method
        # used to justify these numbers once the next checkpoint lands.
        foot_slip_penalty = self._foot_slip_penalty()
        # touchdown_velocity_penalty MUST be computed before
        # _feet_air_time_reward() -- see that method's docstring, it
        # reads self._feet_air_time before feet_air_time_reward() resets
        # it as part of its own landing detection.
        touchdown_velocity_penalty = self._touchdown_velocity_penalty()
        # GATED by forward_progress (2026-08-03, user request) -- same
        # pattern/reason as upright_reward/trot_symmetry_reward/tip_reward:
        # ungated, correct swing-duration cadence is fully collectible
        # (including the per-tick stance-cap penalty component -- see this
        # method's own docstring) whether or not the body ever translates.
        # State tracking (self._feet_air_time/self._feet_stance_time)
        # still updates every call regardless of this gate -- only the
        # REWARD contribution is scaled, not the underlying measurement.
        feet_air_time_reward = self._feet_air_time_reward() * forward_progress

        # Flat, NOT gated by height_progress (unlike the stand task's,
        # see ACTION_RATE_PENALTY_WEIGHT_RISING/STANDING's comment) --
        # walking needs continuous leg motion forever, there's no
        # "should now be still" phase to gate toward here.
        action_rate_penalty = self._action_rate_penalty(action, ACTION_RATE_PENALTY_WEIGHT_RISING)

        # forward_velocity_reward weight raised 2.0 -> 5.0 (2026-07-29):
        # PPO_13000000_walk_policy_v3 measured foot_clearance_reward's
        # weighted contribution at +0.99/step (near its 1.0 ceiling,
        # trivially reached by permanently holding one leg up) against
        # forward_velocity_reward's actual +0.0067/step (the robot
        # wasn't moving, 0.000m traveled over 10s) -- ~148x gap. The
        # FEET_AIR_TIME_MAX_S fix above closes the specific exploit that
        # let clearance hit its ceiling for free, but a genuinely modest
        # walking pace's raw forward_velocity_reward (~0.1-0.3 m/s,
        # cross-referencing walk_policy_v2's 6M/27M runs) still only
        # reached ~0.2-0.6 weighted at the old 2.0 -- smaller than
        # clearance's own 1.0 ceiling, i.e. even a genuinely decent gait
        # wasn't clearly dominant over the (now-closed) exploit. Raised
        # so real forward progress is unambiguously the strongest single
        # term for a reasonable walking pace. Placeholder, not tuned.
        angular_vel_penalty = self._angular_vel_penalty(WALK_ANGULAR_VEL_PENALTY_WEIGHT)

        # -(pitch)^2, already negative -- weight applied externally as a
        # positive coefficient, same convention as foot_slip_penalty/
        # touchdown_velocity_penalty. See _torso_pitch_rad()'s docstring
        # for why up_z's cosine-based upright_reward wasn't sensitive
        # enough to a sustained forward lean on its own.
        pitch_penalty = -(self._torso_pitch_rad() ** 2)

        # SIMPLIFIED-REWARD EXPERIMENT (2026-08-02, `simple_rewards` branch,
        # user request: "only include forward movement, base height").
        # Every OTHER term below is deliberately zeroed via its coefficient,
        # not deleted -- the intent is to test whether real gait coordination
        # can emerge from just forward_velocity_reward + height_reward (this
        # project's own version of the TODO #3 "simplify the reward" fallback
        # in daniel_cl_context.md, inspired by quadrupeds_locomotion's much
        # simpler reward set). Flip any coefficient back to its prior
        # (pre-2026-08-02) value to restore that term -- see git history/
        # daniel_cl_context.md for what each one was before this branch.
        # RESTORED 2026-08-04 (user: torque-control walk checkpoints v5/v6
        # measured genuinely hopping/bounding -- 3-4 legs airborne
        # simultaneously 28-52% of steps, swing feet reaching 0.075-0.20m
        # (2.5-6.7x FOOT_CLEARANCE_TARGET_M), landings as hard as -10.35
        # on touchdown_velocity_penalty's own raw scale, height stuck at
        # 0.20-0.22m vs a 0.28m target -- while forward_velocity_reward
        # alone was weighted 20-30x larger than height_reward, with
        # nothing at all penalizing hard landings or rewarding
        # diagonal-pair alternation over an all-4-legs-together gait.
        # touchdown_velocity_penalty: 0.0 -> 1.0 (direct hard-landing
        # signal). trot_symmetry_reward: 0.0 -> 1.0*WALK_TROT_SYMMETRY_
        # WEIGHT=0.5 (already scoring +0.3 incidentally with zero reward
        # pressure reinforcing it). height_reward: 0.9 -> 2.5 (closer to
        # forward_velocity_reward's scale, real competing incentive to
        # actually rise off a crouch). foot_clearance_reward left at 0.0
        # -- its formula only rewards MORE elevation up to a 0.03m
        # ceiling, doesn't penalize the actual problem (over-jumping to
        # 0.2m), so it wasn't a useful lever here.
        #
        # action_rate_penalty RESTORED 0.0 -> 1.0 (2026-08-04, user:
        # "the robot is not moving smoothly... legs jumping around") --
        # measured on walk_policy_torque_v7 @9M that even with the above
        # restored, 2+ legs were airborne simultaneously 96.5% of the
        # time and mean forward velocity was 0.65 m/s, 4x the "target"
        # speed (see forward_velocity_reward's cap above, added the same
        # day for the same finding). action_rate_penalty directly
        # penalizes jerky tick-to-tick torque changes -- the literal
        # mechanism behind "jumping around" -- and unlike when this was
        # zeroed for STAND (TODO: see that return statement's comment),
        # WALK's own action_rate_weight (ACTION_RATE_PENALTY_WEIGHT_
        # RISING, flat, not height-progress-gated) was already correctly
        # rescaled for torque mode by the 2026-08-04 _action_rate_penalty
        # fix, so this shouldn't reproduce STAND's "won't move at all"
        # regression.
        #
        # non_tip_penalty RESTORED 0.0 -> 1.0 (2026-08-05, alongside
        # MAX_LEG_PHASE_S/CALF_SWING_REWARD_CAP above): the "tumbling"
        # exploit's fatal knee-touch was previously free right up until
        # the instant it triggered NONTIP_TERMINATION_S's hard
        # termination -- no in-episode cost at all beforehand. This adds
        # a direct, immediate per-tick cost for non-tip (knee/shin/thigh)
        # contact, on top of (not instead of) the hard termination and
        # the two gates above -- ungated (see _foot_placement_terms()'s
        # own comment), it discourages knee contact unconditionally,
        # standing-still included.
        #
        # foot_clearance_reward RESTORED 0.0 -> 1.0 (2026-08-06, alongside
        # its Gaussian reformulation above -- see that method's own
        # comment): was zeroed because its old ramp-then-cap formula
        # couldn't penalize over-jumping, not because the underlying idea
        # (dense per-tick reward for lifting a swinging leg) was wrong --
        # now that the formula itself penalizes deviation in both
        # directions, restoring the weight gives the "never lifts a leg
        # at all" failure mode a real gradient pushing against it, which
        # nothing else in this reward currently provides as densely
        # (tip_reward/non_tip_penalty only judge contact AFTER it
        # happens, not the swing trajectory leading up to it).
        return (
            5.0 * forward_velocity_reward
            + 0.5 * upright_reward
            + 2.5 * height_reward
            + 0.0 * tip_reward
            + 1.0 * non_tip_penalty
            + 1.0 * foot_clearance_reward
            + 1.0 * foot_slip_penalty
            + 1.0 * touchdown_velocity_penalty
            + 0.5 * feet_air_time_reward
            + 1.0 * action_rate_penalty
            # angular_vel_penalty RESTORED 0.0 -> 1.0 (2026-08-06, multi-
            # agent review with Gemini's Antigravity CLI, see chatbot.md):
            # found zeroed here with no dated justification anywhere
            # nearby, unlike every other weight in this return statement
            # -- its own dedicated weight constant (WALK_ANGULAR_VEL_
            # PENALTY_WEIGHT=-0.2) was still being computed inside
            # _angular_vel_penalty() the whole time, just discarded by
            # this outer 0.0. No evidence found that this was a
            # deliberate choice (contrast foot_clearance_reward above,
            # which had a specific, dated reason) -- restoring it gives a
            # direct per-tick cost for rapid pitching/tumbling that
            # nothing else in this reward currently provides that densely.
            + 1.0 * angular_vel_penalty
            + 1.0 * WALK_PITCH_PENALTY_WEIGHT * pitch_penalty
            + 1.0 * WALK_TROT_SYMMETRY_WEIGHT * trot_symmetry_reward
            + 0.02 * calf_swing_motion_reward
            + 1.0 * 0.1 # SURVIVAL BONUS: +0.1 per tick just for staying alive
            + 0.0 * self._common_penalties(action)
        )

    def _ensure_viewer(self):
        if self.renderer is None:
            import mujoco.viewer
            self.renderer = mujoco.viewer.launch_passive(
                self.model, self.data, key_callback=self._on_key)
            # Group 3 = the simple collision-primitive geoms (capsules/box)
            # kept alongside the real CAD visual meshes (group 2) for fast
            # collision -- hide them by default so they don't overlap-render
            # with the meshes.
            self.renderer.opt.geomgroup[3] = 0

    def _on_key(self, keycode):
        if keycode == 32:  # GLFW_KEY_SPACE
            self._paused = not self._paused

    def render(self):
        if self.render_mode != 'human':
            return
        self._ensure_viewer()
        self.renderer.sync()

    def close(self):
        if self.renderer is not None:
            self.renderer.close()
            self.renderer = None
