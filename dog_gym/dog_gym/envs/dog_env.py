# TORQUE_BELT mode only (2026-08-05, user request, see
# daniel_cl_context.md's TODO 4 refinement): PD gains for the automatic
# calf belt-compensation servo applied in step()'s
# control_mode='torque_belt' branch, ON TOP of (not replacing) the
# policy's own calf torque -- see that block for the full derivation.
# SIM-ONLY -- there's no matching concept needed on the actuator side
# (unlike TORQUE_KD_GAIN, which must match actuator's torque_kd_gain
# exactly): the servo only exists to compensate for sim's calf joint
# having NO physical belt modeled at all; the real robot's belt already
# does this for free, so a torque_belt-trained policy's calf torque
# output is meant to represent genuine flexion effort only, which
# transfers to real deployment the same way plain 'torque' mode's calf
# output would (straight to set_motor_torque, real belt handles the rest
# natively) -- torque_belt has no separate real-deployment counterpart,
# it only changes SIM training dynamics.
#
# HISTORY: a D-only (velocity-only) version of this servo was tried
# first and directly measured to fail even when applied via the tendon
# (see below) -- a pure damping term can only slow drift, not hold
# against the SUSTAINED disturbance a continuously-applied thigh torque
# represents (same reason the original raw-joint velocity-servo attempt
# failed, see the torque_belt_tendon branch's first commit). A real P
# term (restoring force toward a reference) is required to actually
# hold, not just slow, the drift -- verified directly: KP=30, KD=2 via
# the tendon (below) held within ~10deg of a fixed reference against a
# sustained 15 N*m thigh torque, needing at most ~10 N*m (well inside
# the +-20 N*m budget, no saturation) -- a dramatic improvement over the
# raw-joint velocity-servo's 80-110 N*m requirement and non-convergent
# drift. Still untuned placeholders, not a formal sweep.
#
# WHY THIS DOESN'T FIGHT GENUINE FLEXION: the P term targets the
# ABSOLUTE calf angle AT RESET (self._belt_target_abs_calf, captured
# once per episode -- see reset()), not a hardcoded constant -- matching
# how the walk task's own residual action space is already a deviation
# from a sensible default pose, not an arbitrary reference. The policy's
# own torque is added on top and can still move the calf away from that
# reference for genuine flexion, it just has to additionally overcome
# this gentle spring-like pull (a real but modest cost at these gains,
# not a hard block) -- exactly analogous to how the real belt doesn't
# resist genuine calf-motor effort either, just the passive
# "carried along by the thigh" component.
BELT_SERVO_KP = 30.0
BELT_SERVO_KD = 2.0

# TORQUE_BELT mode only (2026-08-05, user request): per-tick adaptation
# rate for self._belt_target_abs_calf -- see step()'s belt-servo block.
# FIXES a real problem found on stand_policy_torque_belt: a target fixed
# at reset (the sitting/home pose) is a fine reference for a SMALL,
# walking-scale deviation (verified: held within ~10deg against a
# sustained 15 N*m thigh torque), but STAND needs the calf to move
# ~90-105deg away from that reference (STANDING_QPOS_DEG) and hold it
# there for the whole episode -- at BELT_SERVO_KP=30, holding ~1.75rad
# of error requires ~52 N*m just fighting the servo's own spring, which
# alone exceeds the +-20 N*m ctrlrange, leaving little/no budget for
# genuine flexion.
#
# Each tick, BEFORE computing the servo's own P/D terms: target +=
# rate*(current_abs_calf - target) -- a leaky integrator / exponential
# moving average, NOT an instant snap (rate=1.0 would mean target always
# equals current, i.e. zero restoring force ever, defeating the purpose).
# At 100Hz (0.01s/tick), a rate implies a ~dt/rate time constant.
#
# TASK-DEPENDENT since 2026-08-05 (was one shared constant): STAND and
# WALK need very different timescales here, not just different target
# VALUES.
#   - STAND (BELT_TARGET_ADAPT_RATE_STAND=0.02, ~0.5s time constant):
#     resists FAST/transient deviations (like a real breakaway) on a
#     sub-second timescale, but a SUSTAINED, deliberate pose change (a
#     ~1-2s stand-up) has the reference largely catch up within the same
#     episode, instead of the servo fighting the full excursion for the
#     ENTIRE remaining episode. Unchanged from the original value.
#   - WALK (BELT_TARGET_ADAPT_RATE_WALK=0.15, ~0.067s time constant):
#     added after directly measuring the calf not counter-rotating on
#     walk_home_torque_belt v2 -- a real trotting gait cycle measured at
#     ~0.86s/cycle (PPO_9000000_walk_policy_torque_v8, thigh qpos
#     zero-crossings), and belt_pd (the automatic, non-learned servo
#     term) was found to average 1.3-2x LARGER than the policy's own
#     learned action[calf] on every leg -- the ~0.5s STAND time constant
#     is close enough to the gait's own half-cycle (~0.43s) that the
#     servo was actively resisting normal swing-phase motion instead of
#     getting out of its way, drowning out whatever the policy tried to
#     do. 0.15 gives a time constant roughly 1/6 of the gait period --
#     fast enough that the target tracks a normal stride instead of
#     fighting it, while still providing real restoring authority against
#     anything faster than a stride (a slip, a stumble). Untuned
#     placeholder like the STAND value, not a formal sweep.
BELT_TARGET_ADAPT_RATE_STAND = 0.02
BELT_TARGET_ADAPT_RATE_WALK = 0.15

